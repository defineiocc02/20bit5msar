function [cfg,sources]=public_calibration_config(Ppublic)
%PUBLIC_CALIBRATION_CONFIG Whitelisted public projection -> feature cfg17.
% EXACT top fields mapping/digital/control; never pass the analog P or front.
% mapping: plan_rows,pool_seed,dem_enabled,dem_seed,dither_enabled,dither_seed,
%          dither_input_amplitude_v,vref_v (declared public frontend reference).
% digital: vref_v,fsr_diff_v,ra_gain,d2_weights_ra_v,d2_offset_ra_v,
%          tracking_step_ra_v,dither_enabled,dither_seed,dither_amplitude_v,
%          az_mode,tracking_mode,calibration_mode (nominal public codebook).
% control: sample_period_s only. No C/Cf/kappa/held/Qres/target/state accepted.
% Backend14 sources are digital offset, twelve D2 weights, and TA scale (RA V).
% Nominal h scale derives only from gain32 and declared 1024-Cu/eight geometry.
% The public projection permits an enabled zero-amplitude ordinary diagnostic;
% feature generation and the training/Frozen/Bank gate retain stricter eligibility.
    exact(Ppublic,{'mapping';'digital';'control'},'Ppublic');
    map=Ppublic.mapping;
    d=Ppublic.digital;
    c=Ppublic.control;
    exact(map,{'plan_rows';'pool_seed';'dem_enabled';'dem_seed';'dither_enabled'; ...
        'dither_seed';'dither_input_amplitude_v';'vref_v'},'mapping');
    exact(d,{'vref_v';'fsr_diff_v';'ra_gain';'d2_weights_ra_v';'d2_offset_ra_v'; ...
        'tracking_step_ra_v';'dither_enabled';'dither_seed';'dither_amplitude_v'; ...
        'az_mode';'tracking_mode';'calibration_mode'},'digital');
    exact(c,{'sample_period_s'},'control');
    assert(isnumeric(map.plan_rows)&&isreal(map.plan_rows)&&isscalar(map.plan_rows)&& ...
        isfinite(map.plan_rows)&&map.plan_rows==floor(map.plan_rows)&&map.plan_rows>=2&&map.plan_rows<=1e6, ...
        'publicCalConfig:planRows','plan_rows must be an explicit integer 2..1e6.');
    for key={'pool_seed','dem_seed','dither_seed'}
        value=map.(key{1});assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value)&& ...
            value==floor(value)&&value>=0&&value<=2^32-1,'publicCalConfig:seed','Public mapping seeds must be uint32-valued.');
    end
    for key={'dem_enabled','dither_enabled'}
        value=map.(key{1});assert((isnumeric(value)||islogical(value))&&isreal(value)&&isscalar(value)&& ...
            isfinite(double(value))&&any(double(value)==[0 1]),'publicCalConfig:flag','Public flags must be 0/1.');
    end
    assert(isnumeric(d.dither_seed)&&isreal(d.dither_seed)&&isscalar(d.dither_seed)&&isfinite(d.dither_seed)&& ...
        d.dither_seed==floor(d.dither_seed)&&d.dither_seed>=0&&d.dither_seed<=2^32-1, ...
        'publicCalConfig:seed','Digital public dither seed must be uint32-valued.');
    assert(isnumeric(map.dither_input_amplitude_v)&&isreal(map.dither_input_amplitude_v)&& ...
        isscalar(map.dither_input_amplitude_v)&&isfinite(map.dither_input_amplitude_v)&&map.dither_input_amplitude_v>=0, ...
        'publicCalConfig:amplitude','Mapping amplitude must be a finite nonnegative input-equivalent V scalar.');
    assert((isnumeric(d.dither_enabled)||islogical(d.dither_enabled))&&isreal(d.dither_enabled)&& ...
        isscalar(d.dither_enabled)&&ismember(double(d.dither_enabled),[0 1]), ...
        'publicCalConfig:flag','Digital dither flag must be 0/1.');
    assert(isequal(double(map.dither_enabled),double(d.dither_enabled))&& ...
        isequal(double(map.dither_seed),double(d.dither_seed))&& ...
        isequal(double(map.dither_input_amplitude_v),double(d.dither_amplitude_v)), ...
        'publicCalConfig:ditherJoin','Public physical/digital dither flag, seed and INPUT-equivalent amplitude must agree.');
    scalarKeys={'vref_v','fsr_diff_v','ra_gain','d2_offset_ra_v','tracking_step_ra_v','dither_amplitude_v'};
    for k=1:numel(scalarKeys)
        value=d.(scalarKeys{k});assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value), ...
            'publicCalConfig:nominalScalar','Nominal digital scales must be finite real numeric scalars.');
    end
    assert(isnumeric(map.vref_v)&&isreal(map.vref_v)&&isscalar(map.vref_v)&&isfinite(map.vref_v)&& ...
        map.vref_v>0&&map.vref_v==d.vref_v&&d.fsr_diff_v==2*d.vref_v&&d.ra_gain==32&& ...
        d.tracking_step_ra_v>0&&d.dither_amplitude_v>=0, ...
        'publicCalConfig:scaleJoin','Require matching declared Vref/FSR, gain32, positive TA scale and valid input dither amplitude.');
    assert(isnumeric(d.d2_weights_ra_v)&&isreal(d.d2_weights_ra_v)&&numel(d.d2_weights_ra_v)==12&& ...
        all(isfinite(d.d2_weights_ra_v(:)))&&all(d.d2_weights_ra_v(:)>0), ...
        'publicCalConfig:D2weights','Require the twelve public NOMINAL RA-domain D2 weights.');
    assert(((ischar(d.az_mode)&&isrow(d.az_mode))||(isstring(d.az_mode)&&isscalar(d.az_mode)))&& ...
        any(strcmp(d.az_mode,{'off','ordinary','chop','hold','hold_chop'}))&& ...
        strcmp(d.tracking_mode,'finite_sinc2')&&strcmp(d.calibration_mode,'off'), ...
        'publicCalConfig:mode','Use the declared public AZ mode, M8 finite_sinc2 and nominal-off digital codebook.');
    assert(isnumeric(c.sample_period_s)&&isreal(c.sample_period_s)&&isscalar(c.sample_period_s)&& ...
        isfinite(c.sample_period_s)&&c.sample_period_s>0&&1/double(c.sample_period_s)==5e6, ...
        'publicCalConfig:samplePeriod','This feature version requires declared public Ts=200ns.');
    cfg=struct('schema','sar20-behavior-public-cal/v1','vref_v',double(d.vref_v), ...
        'fs_hz',1/double(c.sample_period_s),'plan_rows',double(map.plan_rows), ...
        'pool_seed',double(map.pool_seed),'pool_schedule','causal_18_8_8_2_pm_v1', ...
        'dem_enabled',logical(map.dem_enabled),'dem_seed',double(map.dem_seed),'dem_schedule','pool_cyclic_shift31_v1', ...
        'dither_enabled',logical(map.dither_enabled),'dither_seed',double(map.dither_seed), ...
        'dither_input_amplitude_v',double(map.dither_input_amplitude_v), ...
        'dither_schedule','input_counter_tail1024_over15_v1','az_mode',char(d.az_mode), ...
        'backend_weights_ra_v',[double(d.d2_offset_ra_v);double(d.d2_weights_ra_v(:));double(d.tracking_step_ra_v)], ...
        'nominal_ra_gain',double(d.ra_gain),'tracking_mode','finite_sinc2');
    sources=struct('backend14_offset','Ppublic.digital.d2_offset_ra_v [nominal RA V]', ...
        'backend14_D2','Ppublic.digital.d2_weights_ra_v(1:12) [nominal RA V, MSB first]', ...
        'backend14_TA','Ppublic.digital.tracking_step_ra_v [nominal RA V]', ...
        'gain','Ppublic.digital.ra_gain=32; not actual C/Cf', ...
        'sample_rate','1/Ppublic.control.sample_period_s', ...
        'mapping','Only mapping public flags/seeds/plan length; no capacitance or chip truth', ...
        'parameter_state','none; no coefficient learning, random state or model change');
end
function exact(value,keys,label)
    assert(isstruct(value)&&isscalar(value)&&isequal(sort(fieldnames(value)),sort(keys)), ...
        'publicCalConfig:boundary','%s must contain exactly the declared public whitelist.',label);
end
