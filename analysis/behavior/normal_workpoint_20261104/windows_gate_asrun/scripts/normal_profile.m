function report=normal_profile(jobRoot,candidateManifestSha,gateNames)
% UNFROZEN SCRATCH. Build FSR10 ideal/normal P from the actual 5MS/s N8 P.
% External controller must pin every source/helper, guard paths and use a fresh process.
    jobRoot=normal_jobroot(jobRoot);
    assert(feature('getpid')~=27628&&~usejava('desktop')&&~bdIsLoaded('SarAdc'), ...
        'normalProfile:session','Fresh headless process without a model required.');
    assert(ischar(candidateManifestSha)&&~isempty(regexp(candidateManifestSha,'^[0-9a-f]{64}$','once')), ...
        'normalProfile:sha','Frozen merged manifest SHA required.');
    required={'test_single_rc_ktc','test_joint_ou_az_dac','test_joint_ou_rc_return','test_comparator_single','test_normal_10v'};
    assert(iscell(gateNames)&&all(ismember(required,gateNames)), ...
        'normalProfile:gates','All three merged function gates are required.');
    candidate=fullfile(jobRoot,'candidate');baseline=fullfile(jobRoot,'baseline','single_bank');
    range=fullfile(jobRoot,'range_helpers');reference=fullfile(jobRoot,'reference');
    assert(isfolder(baseline)&&strcmp(sha(fullfile(candidate,'MANIFEST.json')),candidateManifestSha), ...
        'normalProfile:manifest','Candidate/baseline identity missing.');
    assert(strcmp(sha(fullfile(baseline,'MANIFEST.json')),'2cbdffe537b694cef6107ce893ea8bca7f8ef5d95f6ff7d993f020150c6dd514'), ...
        'normalProfile:baseline','Original v2 manifest identity differs.');
    for k=1:numel(gateNames)
        f=fullfile(jobRoot,'gates',gateNames{k},'complete.json');sha(f);
        g=jsondecode(fileread(f));
        expectedStatus='passed';if strcmp(gateNames{k},'test_normal_10v'),expectedStatus='FUNCTION_ASSERTIONS_PASSED';end
        assert(strcmp(g.status,expectedStatus)&&strcmp(g.test,gateNames{k})&& ...
            strcmp(g.candidate_manifest_sha256,candidateManifestSha)&&g.pid~=27628&&~g.model_loaded&& ...
            strcmp(sha(fullfile(jobRoot,'gates',gateNames{k},'report.mat')),g.report_sha256), ...
            'normalProfile:gate','A required merged function gate is missing or changed.');
    end
    baseFile=fullfile(jobRoot,'inputs','P_used.mat');
    assert(strcmp(sha(baseFile),'236ddfb427dfc07e7f7e27dd58746deb30946891717d255b53789aa8127a1e9f'), ...
        'normalProfile:base','Prior actual N8 P identity differs.');
    graph=fullfile(jobRoot,'model','SarAdc.slx');
    assert(strcmp(sha(graph),'48537818b3212e1e4c8231dec433d1fde36d95814cdcce8c529bb2898eb097d3'), ...
        'normalProfile:graph','485 graph identity differs.');
    outdir=fullfile(jobRoot,'profile');assert(~isfolder(outdir)&&~isfile(outdir),'normalProfile:exists','Profile exists.');
    [ok,msg,id]=mkdir(outdir);assert(ok&&isempty(id),'normalProfile:mkdir','%s',msg);
    try
        restoredefaultpath;rehash;cd(jobRoot);
        addpath(genpath(fullfile(candidate,'current','src')),fullfile(candidate,'config'),candidate,range,reference,jobRoot,'-begin');
        assert(same_path(which('normal_parameters'),fullfile(jobRoot,'normal_parameters.m'))&& ...
            same_path(which('normal_10v_configuration'),fullfile(range,'normal_10v_configuration.m')), ...
            'normalProfile:path','Parameter helper resolves outside private sources.');
        base=load(baseFile,'P','P0');assert(isfield(base,'P')&&isfield(base,'P0')&& ...
            sb256_same_bits(base.P,base.P0),'normalProfile:base','Actual N8 P/P0 differ.');
        before=rng;[P,assumptions,ideal]=normal_parameters(base.P);
        [idealCheck,rangeReport,normalNominal]=normal_10v_configuration(base.P);
        rangeGate=load(fullfile(jobRoot,'gates','test_normal_10v','report.mat'),'report','P','normalNominal');
        assert(isequaln(before,rng)&&sb256_same_bits(ideal,idealCheck)&& ...
            sb256_same_bits(ideal,rangeGate.P)&&sb256_same_bits(normalNominal,rangeGate.normalNominal), ...
            'normalProfile:repeat','RNG changed or range outputs differ from v2 function test.');
        assert(P.Ts_s==200e-9&&P.fs_hz==5e6&&P.N==8&&P.fsr_diff_v==10&& ...
            P.front.vref_v==5&&P.digital.vref_v==5&&P.digital.fsr_diff_v==10&& ...
            P.control.sar1.delta_v==10/1024&&P.digital.d1_bias_v==0&& ...
            P.front.single_bank&&~P.front.dem_enabled&&~P.front.dither_enabled&& ...
            ~P.front.jitter.enabled&&~P.transport.enabled&&~P.training.enabled&& ...
            ~P.cal_cfg.enabled&&~P.frozen.enabled&&~P.bank.enabled&& ...
            strcmp(P.digital.calibration_mode,'off'),'normalProfile:scope','Wrong 10V FSR/5MS/s scope.');
        d=P.digital;d.az_mode=ideal.digital.az_mode;
        assert(sb256_same_bits(d,ideal.digital),'normalProfile:decode','Nominal digital weights changed.');
        if isfield(P.ni,'comparator_noise')&&P.ni.comparator_noise
            names=lower(string(gateNames));assert(any(contains(names,'cmp')|contains(names,'comparator')), ...
                'normalProfile:comparatorGate','Active comparator noise requires its separately named merged gate.');
        end
        idealFile=fullfile(outdir,'ideal_P.mat');normalFile=fullfile(outdir,'normal_P.mat');
        save(idealFile,'ideal','-v7.3');save(normalFile,'P','-v7.3');
        save(fullfile(outdir,'assumptions.mat'),'assumptions','rangeReport','normalNominal','-v7.3');
        report=struct('status','prepared','candidate_manifest_sha256',candidateManifestSha, ...
            'base_P_sha256',sha(baseFile),'model_sha256',sha(graph), ...
            'ideal_P_sha256',sha(idealFile),'normal_P_sha256',sha(normalFile), ...
            'assumptions_sha256',sha(fullfile(outdir,'assumptions.mat')), ...
            'normal_parameters_sha256',sha(fullfile(jobRoot,'normal_parameters.m')), ...
            'range_helper_sha256',sha(fullfile(range,'normal_10v_configuration.m')), ...
            'range_nominal_sha256',sha(fullfile(range,'nominal.mat')), ...
            'range_test_status',rangeGate.report.status,'range_test_sha256',sha(fullfile(jobRoot,'gates','test_normal_10v','report.mat')), ...
            'scope','unverified scratch; FSR 10V assumption at 5 MS/s, no ADI/calibration');
        write_new(fullfile(outdir,'complete.json'),report);
    catch ex
        try,write_new(fullfile(outdir,'failed.json'),struct('status','failed','id',ex.identifier, ...
                'error',getReport(ex,'extended','hyperlinks','off')));catch,end
        rethrow(ex)
    end
end
function yes=same_path(a,b)
    yes=~isempty(a)&&strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath()));
end
function yes=under(path,root)
    if isempty(path),yes=false;return;end
    a=lower(strrep(char(java.io.File(char(path)).getCanonicalPath()),'\','/'));
    b=lower(strrep(char(java.io.File(char(root)).getCanonicalPath()),'\','/'));
    yes=strcmp(a,b)||startsWith(a,[b '/']);
end
function h=sha(file)
    d=dir(file);assert(isscalar(d)&&~d.isdir&&d.bytes<=300000000,'normalProfile:size','Missing or oversized: %s',file);
    f=fopen(file,'rb');assert(f>=0,'normalProfile:read','Cannot read: %s',file);c=onCleanup(@()fclose(f)); %#ok<NASGU>
    x=fread(f,Inf,'*uint8');md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(x(:),'int8'));
    h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_new(file,x)
    assert(~isfile(file)&&~isfolder(file),'normalProfile:exists','Receipt exists.');
    f=fopen(file,'w','n','UTF-8');assert(f>=0,'normalProfile:write','Cannot write receipt.');c=onCleanup(@()fclose(f)); %#ok<NASGU>
    fwrite(f,[jsonencode(x) newline],'char');
end
