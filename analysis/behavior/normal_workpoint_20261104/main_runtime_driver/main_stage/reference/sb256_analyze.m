function [selected,metadata,metrics,validation]=sb256_analyze(simout,P,n8out,P0)
% Actual N256 codes, fixed-calendar evidence and same-graph N8 prefix check.
% No input generation, no ideal-code substitution, and no hidden FE state claim.
    assert(isa(simout,'Simulink.SimulationOutput')&&isempty(simout.ErrorMessage)&& ...
        isa(n8out,'Simulink.SimulationOutput')&&isempty(n8out.ErrorMessage), ...
        'sb256:output','Require actual completed N256 and N8 outputs.');
    [te,e]=sb256_series(simout,'event_log',2);
    [tr,raw]=sb256_series(simout,'raw_log',6);[ty,ready]=sb256_series(simout,'ready_log',1);
    [tc,control]=sb256_series(simout,'control_log',13);
    assert(sb256_same_bits(te,tr)&&sb256_same_bits(te,ty)&&sb256_same_bits(te,tc), ...
        'sb256:axis','Actual event/raw/ready/control time axes differ.');
    G=numel(P.groups);cycles=P.schedule.n_cycles;
    assert(G==48&&cycles==260&&isequal(e,[repelem((0:cycles-1).',G) repmat((1:G).',cycles,1)]), ...
        'sb256:events','Need complete 260 x 48 actual event groups.');
    expectedTime=zeros(size(te));rawRows=false(size(te));inventory=zeros(1,5);
    for g=1:G
        events=P.groups(g).events;types={events.type};rows=e(:,2)==g;
        expectedTime(rows)=e(rows,1)*P.Ts_s+P.groups(g).time_s;
        rawRows(rows)=any(strcmp(types,'raw_latch'));
        names={'d2_decide','d2_feedback','ta_compare','ta_feedback','raw_latch'};
        for k=1:numel(names),inventory(k)=inventory(k)+sum(strcmp(types,names{k}));end
    end
    assert(sb256_same_bits(te,expectedTime)&&isequal(inventory,[12 12 8 7 1])&& ...
        isequal(double(ready),double(rawRows))&&nnz(rawRows)==cycles, ...
        'sb256:calendar','Actual event times, RAW readiness or scheduled counts differ.');
    actual=raw(rawRows,:);ctl=control(rawRows,:);
    assert(isequal(actual(:,4),(0:cycles-1).')&&all(actual(:,5)==P.epoch)&& ...
        all(actual(:,6)==1)&&isequal(actual(:,1:3),ctl(:,5:7))&&all(ctl(:,8)==1), ...
        'sb256:raw','All 260 actual RAW/ID/epoch/valid values must match control.');
    V=behavior_record_view(simout,P);
    assert(sb256_same_bits(V.observed_raw,actual)&& ...
        sb256_same_bits(V.observed_ready_time_s,te(rawRows)), ...
        'sb256:recordJoin','Direct record RAW/time differs from the actual ADC RAW/ready wires.');
    assert(size(V.raw,1)==256&&isequal(V.raw(:,4),(4:259).')&& ...
        all(V.raw(:,5)==P.epoch)&&all(V.raw(:,6)==1)&& ...
        all(isfinite(V.code20)&V.code20==floor(V.code20)&V.code20>=0&V.code20<2^20), ...
        'sb256:selected','Need 256 actual consecutive valid unsigned20 records.');
    V8=behavior_record_view(n8out,P0);
    assert(size(V8.raw,1)==8&&sb256_same_bits(V.raw(1:8,:),V8.raw)&& ...
        sb256_same_bits(V.code20(1:8),V8.code20)&&sb256_same_bits(V.time_s(1:8),V8.time_s), ...
        'sb256:n8Prefix','First eight actual RAW/code/time values differ from the same-graph N8.');
    selected=struct('raw',V.raw,'code20',V.code20,'time_s',V.time_s, ...
        'observed_raw',V.observed_raw,'observed_ready_time_s',V.observed_ready_time_s, ...
        'raw_fields',{{'D1','D2','DT','ID','epoch','valid'}});
    metadata=struct('fs_hz',P.fs_hz,'fsr_diff_v',P.fsr_diff_v,'stimulus',P.input);
    metrics=behavior_spectrum(selected.code20,metadata);
    assert(strcmp(metrics.status,'actual_codes_characterized')&&metrics.fundamental_bin==5&& ...
        metrics.record_length==256,'sb256:spectrum','Actual 256-code coherent bin5 spectrum required.');
    fields={'snr_db','sndr_db','sfdr_db','thd_db','enob'};
    for k=1:numel(fields)
        v=metrics.(fields{k});assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&~isnan(v), ...
            'sb256:metric','Metric %s is undefined.',fields{k});
    end
    clip=sum(V.code20==0|V.code20==2^20-1);
    validation=struct('status','actual_256_codes_characterized','sample_ids',(4:259), ...
        'n_cycles',cycles,'event_rows',size(e,1),'scheduled_token_counts',inventory, ...
        'physical_feedback_counter','UNOBSERVED_DEBUG_OFF', ...
        'n8_prefix_raw_code_time_bit_equal',true,'endpoint_code_count',clip, ...
        'record_boundary',V.readiness_boundary, ...
        'scope','Actual model record; 256-point spectrum, not 20k-point paper measurement or PDK signoff.');
end
