function report=test_behavior_spectrum_collision(original_dir,candidate_dir,selected_mat,spectrum_mat)
%TEST_BEHAVIOR_SPECTRUM_COLLISION Regression for actual behavior_spectrum files.
% Synthetic suite: test_behavior_spectrum_collision(original_dir,candidate_dir)
% Historical suite: test_behavior_spectrum_collision(original_dir,candidate_dir, ...
%                                   absolute_selected_mat,absolute_spectrum_mat)
% Omit paths 1/2 to use original/ and candidate/ beside this test. When the
% selected path is given, spectrum.mat defaults to its directory and MUST exist.
% This function reads the inputs and creates uniquely named function copies
% in a temporary directory. It never changes folders or clears production code;
% the prior MATLAB path is restored and the scratch directory is removed.
% No simulink model is opened, no sampling data are generated by the DUT,
% no tolerance is applied to legacy/candidate or stored-metrics comparisons.
    root=fileparts(mfilename('fullpath'));
    if nargin<1||isempty(original_dir),original_dir=fullfile(root,'original');end
    if nargin<2||isempty(candidate_dir),candidate_dir=fullfile(root,'candidate');end
    if nargin<3,selected_mat='';end
    if nargin<4,spectrum_mat='';end
    assert(isfile(fullfile(original_dir,'behavior_spectrum.m')), ...
        'SpectrumTest:missingOriginal','Original implementation not found.');
    assert(isfile(fullfile(candidate_dir,'behavior_spectrum.m')), ...
        'SpectrumTest:missingCandidate','Candidate implementation not found.');
    [old_fn,new_fn,session_cleanup]=make_test_handles(original_dir,candidate_dir); %#ok<NASGU>

    % A single sampled sequence can come from distinct H1/H3 decompositions.
    N=256;n=(0:N-1).';pattern=[1;0;-1;0];
    w1=pattern(mod(n,4)+1);w3=pattern(mod(3*n,4)+1);
    deterministic_noise=mod(37*n+17,29)-14;
    code64a=2^19+120000*w1+40000*w3+deterministic_noise;
    code64b=2^19+160000*w1+deterministic_noise;
    assert_bits_equal(code64a,code64b,'H1/H3 counterexample code');
    p64=make_parameters(64,N);
    old64=invoke(old_fn,code64a,p64);
    assert(strcmp(old64.status,'actual_codes_characterized')&& ...
        all(isfield(old64,{'snr_db','sndr_db','sfdr_db','thd_db','enob'})), ...
        'SpectrumTest:baselineDidNotReproduce', ...
        'Original must reproduce the incorrect characterized status at bin 64.');
    fprintf('BASELINE RED: bin 64 returns metrics although H3 and H1 are indistinguishable.\n');
    new64=invoke(new_fn,code64a,p64);
    validate_collision(new64,old64,64,N);
    assert(any_collision(new64,'fundamental',3,1,64), ...
        'SpectrumTest:missingH3Fundamental','Expected H3/H1 collision missing.');
    assert(any_collision(new64,'dc',4,0,0), ...
        'SpectrumTest:missingH4DC','Expected H4/DC collision missing.');
    fprintf('CANDIDATE GREEN: bin 64 collision is explicit and all five metrics are absent.\n');

    % Every legal fundamental at N=256, including aliasing and even bin 8.
    counts=struct('valid',0,'collision',0);
    for bin=1:127
        codes=make_codes(bin,N);p=make_parameters(bin,N);
        before=invoke(old_fn,codes,p);
        after=invoke(new_fn,codes,p);
        expected=collision_matrix(bin,N);
        if any(expected(:))
            validate_collision(after,before,bin,N);
            counts.collision=counts.collision+1;
        else
            assert_bits_equal(after,before,sprintf('legacy output bin %d',bin));
            counts.valid=counts.valid+1;
        end
    end
    assert(counts.valid==120&&counts.collision==7,'SpectrumTest:unexpectedCounts', ...
        'Expected 120 valid and 7 colliding fundamental bins for N=256.');
    p=make_parameters(8,N);c=make_codes(8,N);
    ok8=invoke(new_fn,c,p);
    assert(strcmp(ok8.status,'actual_codes_characterized'), ...
        'SpectrumTest:validEvenBin','Legal even bin 8 must remain accepted.');
    assert_bits_equal(ok8,invoke(old_fn,c,p),'legal even bin 8');
    p=make_parameters(16,N);c=make_codes(16,N);
    bad16=invoke(new_fn,c,p);
    assert(any_collision(bad16,'harmonic',9,7,112), ...
        'SpectrumTest:missingH7H9','Expected H7/H9 collision at bin 112 missing.');
    assert(~any(strcmp({bad16.harmonic_collisions.kind},'dc'))&& ...
        ~any(strcmp({bad16.harmonic_collisions.kind},'fundamental')), ...
        'SpectrumTest:wrongCollisionKind','Bin 16 must have only harmonic/harmonic collisions.');
    p=make_parameters(32,N);c=make_codes(32,N);
    bad32=invoke(new_fn,c,p);
    assert(any_collision(bad32,'dc',8,0,0)&& ...
        any_collision(bad32,'fundamental',7,1,32), ...
        'SpectrumTest:missingBin32','Expected bin-32 DC/fundamental collisions missing.');
    % Strictly periodic quantized data can have zero separately resolvable noise.
    % This still must return the collision status, not the legacy power error.
    cycle=repmat([524288;594999;624288;594999;524288;453577;424288;453577],32,1);
    cycle_result=invoke(new_fn,cycle,p);
    assert(strcmp(cycle_result.status,'harmonic_alias_collision')&& ...
        ~any(isfield(cycle_result,{'snr_db','sndr_db','sfdr_db','thd_db','enob'})), ...
        'SpectrumTest:zeroNoiseCollision','Periodic zero-noise collision must be reported.');
    assert(any_collision(cycle_result,'dc',8,0,0), ...
        'SpectrumTest:zeroNoiseDiagnostic','Periodic collision detail missing.');
    fprintf('PASS: all N=256 bins: %d legacy-identical, %d collision statuses.\n',counts.valid,counts.collision);

    % These original contracts are not widened, including strict <1e-9.
    short_old=invoke(old_fn,zeros(255,1),struct());
    short_new=invoke(new_fn,zeros(255,1),struct());
    assert_bits_equal(short_new,short_old,'short capture');
    assert(strcmp(short_new.status,'not_run_short_capture'),'SpectrumTest:shortStatus', ...
        'N<256 must retain not_run_short_capture.');
    c=make_codes(5,N);p=make_parameters(5,N);p.stimulus.frequency_hz=5+0.5e-9;
    assert_bits_equal(invoke(new_fn,c,p),invoke(old_fn,c,p),'coherence inside tolerance');
    p.stimulus.frequency_hz=5+2e-9;
    assert_error(@()invoke(old_fn,c,p),'BehaviorSpectrum:coherence');
    assert_error(@()invoke(new_fn,c,p),'BehaviorSpectrum:coherence');
    assert_error(@()invoke(old_fn,zeros(258,1),p),'BehaviorSpectrum:length');
    assert_error(@()invoke(new_fn,zeros(258,1),p),'BehaviorSpectrum:length');
    p=make_parameters(32,N);constant_codes=repmat(2^19,N,1);
    assert_error(@()invoke(old_fn,constant_codes,p),'BehaviorSpectrum:power');
    assert_error(@()invoke(new_fn,constant_codes,p),'BehaviorSpectrum:power');
    fprintf('PASS: short capture, coherence threshold and length/degenerate-power error identifiers.\n');

    report=struct('synthetic_suite','pass','valid_bins',counts.valid, ...
        'collision_bins',counts.collision,'historical_suite','not_run');
    if ~isempty(selected_mat)
        if isempty(spectrum_mat),spectrum_mat=fullfile(fileparts(selected_mat),'spectrum.mat');end
        assert(isfile(selected_mat)&&isfile(spectrum_mat),'SpectrumTest:missingHistory', ...
            'Both selected.mat and spectrum.mat must exist for historical validation.');
        s=load(selected_mat,'selected','metadata');
        r=load(spectrum_mat,'metrics');
        assert(all(isfield(s,{'selected','metadata'}))&&isfield(s.selected,'code20')&& ...
            isfield(r,'metrics'),'SpectrumTest:historySchema', ...
            'Expected selected.code20, metadata and metrics variables.');
        code=s.selected.code20;meta=s.metadata;
        assert(numel(code)==256&&round(meta.stimulus.frequency_hz*256/meta.fs_hz)==5, ...
            'SpectrumTest:notHistoricalBin5','Historical input must be N=256 and bin 5.');
        old_real=invoke(old_fn,code,meta);
        new_real=invoke(new_fn,code,meta);
        assert_bits_equal(new_real,old_real,'historical candidate versus original');
        assert_bits_equal(old_real,r.metrics,'historical original versus stored spectrum.mat metrics');
        report.historical_suite='pass';
        report.selected_mat=selected_mat;report.spectrum_mat=spectrum_mat;
        fprintf('PASS: historical N=256 bin 5: candidate, original and stored metrics match field by field and bit for bit.\n');
    else
        fprintf('NOT RUN: historical real-code/saved-spectrum comparison (paths were not supplied).\n');
    end
end

function p=make_parameters(bin,N)
    p=struct('fs_hz',256,'fsr_diff_v',2, ...
        'stimulus',struct('frequency_hz',bin*256/N,'amplitude_v',1,'phase_rad',0.13));
end

function codes=make_codes(bin,N)
    n=(0:N-1).';folded=fold_orders(bin,N);
    available=setdiff(1:N/2-1,unique([bin folded]));
    assert(~isempty(available),'SpectrumTest:noNoiseBin','No independent fixture noise bin.');
    noise_bin=available(1);
    codes=2^19+round(130000*cos(2*pi*bin*n/N+0.13)+ ...
        11000*cos(2*pi*2*bin*n/N-0.4)+4000*cos(2*pi*3*bin*n/N+0.8)+ ...
        61*cos(2*pi*noise_bin*n/N+0.4));
    assert(all(codes>=0&codes<2^20),'SpectrumTest:badFixture','Fixture outside 20-bit range.');
end

function y=invoke(fn,codes,p)
    y=fn(codes,p);
end

function [old_fn,new_fn,guard]=make_test_handles(original_dir,candidate_dir)
    previous_path=path;
    scratch=tempname;
    [ok,msg]=mkdir(scratch);
    assert(ok,'SpectrumTest:mkdir','Cannot create isolated temporary directory: %s',msg);
    guard=onCleanup(@()cleanup_test_handles(previous_path,scratch));
    [~,tag]=fileparts(scratch);
    tag=regexprep(tag,'[^A-Za-z0-9_]','_');
    tag=tag(max(1,numel(tag)-19):end);
    old_name=['sar20_fft_old_' tag];new_name=['sar20_fft_new_' tag];
    rename_copy(fullfile(original_dir,'behavior_spectrum.m'),fullfile(scratch,[old_name '.m']),old_name);
    rename_copy(fullfile(candidate_dir,'behavior_spectrum.m'),fullfile(scratch,[new_name '.m']),new_name);
    addpath(scratch,'-begin');
    assert(strcmp(which(old_name),fullfile(scratch,[old_name '.m']))&& ...
        strcmp(which(new_name),fullfile(scratch,[new_name '.m'])), ...
        'SpectrumTest:sourceResolution','Temporary test functions did not resolve correctly.');
    old_fn=str2func(old_name);new_fn=str2func(new_name);
end

function rename_copy(source,target,name)
    body=fileread(source);
    header='function result=behavior_spectrum(code20,p)';
    assert(strncmp(body,header,numel(header)),'SpectrumTest:sourceHeader', ...
        'Unexpected behavior_spectrum function declaration in %s.',source);
    body=['function result=' name '(code20,p)' body(numel(header)+1:end)];
    [fid,msg]=fopen(target,'wb');
    assert(fid>=0,'SpectrumTest:temporaryWrite','Cannot write isolated function copy: %s',msg);
    file_guard=onCleanup(@()fclose(fid)); %#ok<NASGU>
    count=fwrite(fid,body,'char');
    assert(count==numel(body),'SpectrumTest:temporaryWrite','Incomplete isolated function copy.');
end

function cleanup_test_handles(previous_path,scratch)
    path(previous_path);
    if isfolder(scratch),rmdir(scratch,'s');end
end

function folded=fold_orders(bin,N)
    folded=zeros(1,9);
    for h=2:10
        value=mod(h*bin,N);
        if value>N/2,value=N-value;end
        folded(h-1)=value;
    end
end

function expected=collision_matrix(bin,N)
    bins=[0 bin fold_orders(bin,N)];expected=false(11,11);
    for a=1:10
        for b=a+1:11
            expected(a,b)=bins(a)==bins(b);
        end
    end
end

function validate_collision(actual,baseline,bin,N)
    assert(strcmp(actual.status,'harmonic_alias_collision'), ...
        'SpectrumTest:collisionNotReported','N=%d bin %d collision status missing.',N,bin);
    forbidden={'snr_db','sndr_db','sfdr_db','thd_db','enob'};
    assert(~any(isfield(actual,forbidden)),'SpectrumTest:invalidMetricPresent', ...
        'N=%d bin %d has a forbidden metric field.',N,bin);
    assert(actual.fundamental_bin==bin&&isequal(actual.harmonic_orders,2:10)&& ...
        isequal(actual.harmonic_folded_bins,fold_orders(bin,N)), ...
        'SpectrumTest:foldedBins','N=%d bin %d incorrect diagnostic bins.',N,bin);
    for field={'frequency_hz','power_v2','dc_voltage_v'}
        f=field{1};assert_bits_equal(actual.(f),baseline.(f),['collision diagnostics.' f]);
    end
    got=false(11,11);
    for j=1:numel(actual.harmonic_collisions)
        c=actual.harmonic_collisions(j);h=c.harmonic_order;other=c.other_order;
        assert(h>=2&&h<=10&&other>=0&&other<h&&h==floor(h)&&other==floor(other), ...
            'SpectrumTest:collisionOrder','Invalid collision pair.');
        if other==0,kind='dc';elseif other==1,kind='fundamental';else,kind='harmonic';end
        assert(strcmp(c.kind,kind),'SpectrumTest:collisionKind','Incorrect collision kind.');
        folded=fold_orders(bin,N);
        assert(c.bin==folded(h-1),'SpectrumTest:collisionBin','Incorrect collision bin.');
        assert(~got(other+1,h+1),'SpectrumTest:duplicateCollision','Duplicate collision record.');
        got(other+1,h+1)=true;
    end
    assert(isequal(got,collision_matrix(bin,N)),'SpectrumTest:collisionPairs', ...
        'N=%d bin %d missing or spurious collision pairs.',N,bin);
end

function yes=any_collision(result,kind,h,other,bin)
    yes=false;
    for j=1:numel(result.harmonic_collisions)
        c=result.harmonic_collisions(j);
        if strcmp(c.kind,kind)&&c.harmonic_order==h&&c.other_order==other&&c.bin==bin
            yes=true;return
        end
    end
end

function assert_error(f,identifier)
    try
        f();
    catch cause
        assert(strcmp(cause.identifier,identifier),'SpectrumTest:wrongError', ...
            'Expected %s, received %s.',identifier,cause.identifier);
        return
    end
    error('SpectrumTest:missingError','Expected error %s.',identifier);
end

function assert_bits_equal(a,b,label)
    assert(strcmp(class(a),class(b))&&isequal(size(a),size(b)), ...
        'SpectrumTest:shapeOrClass','%s: class or size changed.',label);
    if isstruct(a)
        fields=fieldnames(a);
        assert(isequal(fields,fieldnames(b)),'SpectrumTest:fields', ...
            '%s: field names or field order changed.',label);
        for i=1:numel(a)
            for j=1:numel(fields)
                f=fields{j};assert_bits_equal(a(i).(f),b(i).(f),[label '.' f]);
            end
        end
    elseif iscell(a)
        for i=1:numel(a),assert_bits_equal(a{i},b{i},sprintf('%s{%d}',label,i));end
    elseif isnumeric(a)
        assert(isreal(a)&&isreal(b)&&~issparse(a)&&~issparse(b), ...
            'SpectrumTest:unsupportedType','%s: complex/sparse numeric not supported.',label);
        assert(isequal(typecast(a(:),'uint8'),typecast(b(:),'uint8')), ...
            'SpectrumTest:bits','%s: numeric bits changed.',label);
    elseif islogical(a)||ischar(a)
        assert(isequal(a,b),'SpectrumTest:value','%s: value changed.',label);
    else
        error('SpectrumTest:unsupportedType','%s: unsupported class %s.',label,class(a));
    end
end
