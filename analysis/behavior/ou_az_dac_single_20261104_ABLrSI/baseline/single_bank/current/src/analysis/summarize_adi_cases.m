function report=summarize_adi_cases(runDirs,suite)
%SUMMARIZE_ADI_CASES Pure posterior summary of eight completed SAR20 N8 runs.
% runDirs: eight actual SAR20 run directories, ordered as suite.cases.
% Reads parameters.mat/selected.mat/simout.mat/summary.json; never simulates,
% changes configuration, draws chip/noise, or writes files. Caller saves output.
% Error reference is configured input sine evaluated at ACTUAL CNV log times;
% code-center reconstruction is nominal public transfer, not internal truth.
% No FFT/SNDR/ENOB, fit/calibration, or statistical benefit inference from N8.
    if isstring(runDirs),runDirs=cellstr(runDirs);end
    assert(iscell(runDirs)&&numel(runDirs)==8&&isstruct(suite)&&numel(suite.cases)==8, ...
        'adiSummary:inputs','Supply eight actual run paths ordered as suite.cases.');
    C=cell(8,1);parameters=cell(8,1);
    for k=1:8
        folder=char(runDirs{k});expected=suite.cases(k);
        summary=jsondecode(fileread(fullfile(folder,'summary.json')));
        assert(strcmp(summary.status,'complete')&&summary.simulation_completed, ...
            'adiSummary:complete','Run %s is not complete.',folder);
        a=load(fullfile(folder,'parameters.mat'),'P');P=a.P;parameters{k}=P;
        assert(P.N==8&&P.N==expected.P.N&&P.first_id==expected.P.first_id&& ...
            P.epoch==expected.P.epoch&&P.Ts_s==expected.P.Ts_s&& ...
            isequaln(P.input,expected.P.input)&&isequaln(P.front.C_f,expected.P.front.C_f)&& ...
            P.front.dem_enabled==expected.dem_enabled&&P.front.dither_enabled==expected.dither_enabled&& ...
            isequaln(P.digital,expected.P.digital),'adiSummary:caseIdentity', ...
            'Actual saved P differs from ordered suite case %s.',expected.name);
        assert(strcmp(P.digital.calibration_mode,'off'),'adiSummary:calibration','Require uncalibrated cases.');
        s=load(fullfile(folder,'selected.mat'),'selected','metadata');selected=s.selected;
        a=load(fullfile(folder,'simout.mat'),'simout');out=a.simout;
        assert(isa(out,'Simulink.SimulationOutput')&&isempty(out.ErrorMessage), ...
            'adiSummary:actualOutput','Require completed actual SimulationOutput.');
        [t,raw]=series(out.get('raw_log'),6);[ct,code]=series(out.get('code_log'),1);
        [rt,ready]=series(out.get('ready_log'),1);[et,event]=series(out.get('event_log'),2);
        assert(isequal(t,ct)&&isequal(t,rt)&&isequal(t,et),'adiSummary:axes','Actual logger axes differ.');
        take=ready==1&raw(:,4)>=P.first_id&raw(:,4)<P.first_id+P.N;
        actualRaw=raw(take,:);actualCode=code(take);rawTime=t(take);ids=actualRaw(:,4);
        assert(isequal(ids,(P.first_id:P.first_id+7).')&&all(actualRaw(:,5)==P.epoch)&& ...
            all(actualRaw(:,6)==1)&&isequaln(selected.raw,actualRaw)&& ...
            isequaln(selected.code20(:),actualCode)&&isequaln(selected.time_s(:),rawTime), ...
            'adiSummary:selected','Saved selected data differs from actual ready RAW/code/time wires.');
        assert(all(actualCode==floor(actualCode)&actualCode>=0&actualCode<2^20)&& ...
            s.metadata.fsr_diff_v==P.fsr_diff_v,'adiSummary:code','Actual code range/nominal scale mismatch.');
        cnvGroups=[];
        for g=1:numel(P.groups)
            if any(strcmp({P.groups(g).events.type},'cnv')),cnvGroups(end+1)=g;end %#ok<AGROW>
        end
        assert(isscalar(cnvGroups),'adiSummary:cnv','Require one CNV group per sample.');
        captureTime=zeros(8,1);
        for sample=1:8
            row=find(event(:,1)==ids(sample)&event(:,2)==cnvGroups);
            assert(isscalar(row),'adiSummary:cnvLog','Missing/duplicate actual CNV time.');
            captureTime(sample)=t(row);
        end
        u=P.input;
        reference=u.offset_v+u.amplitude_v*sin(2*pi*u.frequency_hz*captureTime+u.phase_rad);
        lsb=P.fsr_diff_v/2^20;voltage=(actualCode-2^19)*lsb;
        error=voltage-reference;
        C{k}=struct('name',expected.name,'chip',expected.chip, ...
            'dem_enabled',logical(P.front.dem_enabled),'dither_enabled',logical(P.front.dither_enabled), ...
            'run_path',folder,'elapsed_sim_s',summary.elapsed_s,'records',8, ...
            'sample_id',ids,'epoch',actualRaw(:,5),'raw_time_s',rawTime,'cnv_time_s',captureTime, ...
            'raw_D1_D2_DT',actualRaw(:,1:3),'code20',actualCode, ...
            'code_min',min(actualCode),'code_max',max(actualCode),'code_p2p_counts',max(actualCode)-min(actualCode), ...
            'nominal_lsb_v',lsb,'code_center_v',voltage,'code_center_p2p_v',p2p(voltage), ...
            'input_reference_v',reference,'input_reference_p2p_v',p2p(reference), ...
            'error_to_input_reference_v',error,'error_mean_v',mean(error), ...
            'error_rms_v',sqrt(mean(error.^2)),'error_p2p_v',p2p(error), ...
            'error_max_abs_v',max(abs(error)),'error_rms_lsb',sqrt(mean((error/lsb).^2)), ...
            'rail_code_count',sum(actualCode==0|actualCode==2^20-1), ...
            'model_sha256',summary.model_sha256,'config_sha256',summary.config_sha256, ...
            'input_reference_scope','Configured input waveform at actual CNV times; not held/internal truth; no gain/offset fit');
    end
    cases=vertcat(C{:});pairs=struct('chip',{},'switched',{},'fixed_other',{}, ...
        'off_case',{},'on_case',{},'sample_id',{},'code_delta_on_minus_off',{}, ...
        'raw_delta_on_minus_off',{},'changed_codes',{},'changed_raw_words',{}, ...
        'code_delta_max_abs_counts',{},'code_center_delta_p2p_v',{}, ...
        'error_rms_delta_on_minus_off_v',{},'error_max_abs_delta_on_minus_off_v',{});
    chips=unique({cases.chip},'stable');
    for ci=1:numel(chips)
        for sw=1:2
            for fixed=0:1
                sameChip=strcmp({cases.chip},chips{ci});
                if sw==1
                    off=find(sameChip&~[cases.dem_enabled]&[cases.dither_enabled]==logical(fixed));
                    on=find(sameChip&[cases.dem_enabled]&[cases.dither_enabled]==logical(fixed));
                    switched='DEM';other=sprintf('dither=%d',fixed);
                else
                    off=find(sameChip&[cases.dem_enabled]==logical(fixed)&~[cases.dither_enabled]);
                    on=find(sameChip&[cases.dem_enabled]==logical(fixed)&[cases.dither_enabled]);
                    switched='dither';other=sprintf('DEM=%d',fixed);
                end
                assert(isscalar(off)&&isscalar(on),'adiSummary:pair','Missing/duplicate switch pair.');
                x=cases(off);y=cases(on);
                assert(isequal(x.sample_id,y.sample_id)&&isequal(x.cnv_time_s,y.cnv_time_s)&& ...
                    isequal(x.input_reference_v,y.input_reference_v)&& ...
                    isequal(parameters{off}.front.C_f,parameters{on}.front.C_f), ...
                    'adiSummary:pairIdentity','Pair changed chip/input/sample identity.');
                dc=y.code20-x.code20;dr=y.raw_D1_D2_DT-x.raw_D1_D2_DT;
                pairs(end+1)=struct('chip',chips{ci},'switched',switched,'fixed_other',other, ...
                    'off_case',x.name,'on_case',y.name,'sample_id',x.sample_id, ...
                    'code_delta_on_minus_off',dc,'raw_delta_on_minus_off',dr, ...
                    'changed_codes',sum(dc~=0),'changed_raw_words',sum(dr~=0,1), ...
                    'code_delta_max_abs_counts',max(abs(dc)), ...
                    'code_center_delta_p2p_v',p2p(y.code_center_v-x.code_center_v), ...
                    'error_rms_delta_on_minus_off_v',y.error_rms_v-x.error_rms_v, ...
                    'error_max_abs_delta_on_minus_off_v',y.error_max_abs_v-x.error_max_abs_v); %#ok<AGROW>
            end
        end
    end
    report=struct('schema','sar20-adi-eight-actual-run-summary/v1','cases',cases,'switch_pairs',pairs, ...
        'scope','Eight-sample descriptive posterior comparison; input reference only; no FFT, fit, calibration or benefit claim', ...
        'error_reference','Configured input waveform evaluated at actual logged CNV time; public nominal code-center reconstruction', ...
        'pair_delta_convention','on minus off; signed error-stat differences describe only these eight samples', ...
        'global_rng_scope','Caller owns actual simulation RNG gate; this function uses no RNG');
end
function value=p2p(x),value=max(x)-min(x);end
function [t,x]=series(s,width)
    assert(isa(s,'timeseries')&&isa(s.Data,'double')&&isreal(s.Data),'adiSummary:logger','Require real actual timeseries.');
    t=s.Time(:);x=squeeze(s.Data);
    if width==1,x=x(:);elseif size(x,1)~=numel(t),x=x.';end
    assert(isequal(size(x),[numel(t) width])&&all(isfinite(t))&&all(diff(t)>0), ...
        'adiSummary:shape','Actual logger shape/time axis invalid.');
end
