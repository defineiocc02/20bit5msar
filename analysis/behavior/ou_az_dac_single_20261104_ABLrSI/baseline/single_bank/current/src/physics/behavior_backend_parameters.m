function p = behavior_backend_parameters(saved, A)
%BEHAVIOR_BACKEND_PARAMETERS Build explicit low-order RA/AZ/CINC parameters.
%Version: v2 AZ (2026-10-27). Caller: current SAR20 configuration and backend checks.
%Inputs: saved is the small nominal.mat design struct passed by adc_parameters,
%not the old full SAR20_P/PoolAnalogCfg; explicit A.A0 [1], UGB_hz [Hz],
%Cf_f [F], tau_reset_s [s]. Output p is behavior-backend-parameters/v1.
%Qres/Cf and Ctop/Cf must share the same half/differential normalization;
%front-end Ctop excludes the separate CT output load. Inf A0/UGB idealizes each.
%No retained state/reset/RNG. Assumptions are not inferred from a paper.
%Model: one closed-loop RA pole, ideal common mode/A reset, retained floating B,
%zero replica delay; RA OU defaults OFF, other noise/nonlinear options disabled.
    assert(isstruct(A)&&all(isfield(A,{'A0','UGB_hz','Cf_f','tau_reset_s'})), ...
        'behavior:assumptions','Explicit A0, UGB_hz, Cf_f, tau_reset_s required.');
    p=struct('schema','behavior-backend-parameters/v1', ...
        'units','V, F, C, s, Hz; all signs use sar20_cdac2_network convention');
    p.ra=struct('A0',double(A.A0),'UGB_hz',double(A.UGB_hz), ...
        'Cf_f',double(A.Cf_f),'tau_reset_s',double(A.tau_reset_s), ...
        'vos_input_v',0,'slew_v_per_s',Inf);
    p.az=struct('write_tau_s',[1e-9;1e-9],'leak_tau_s',[Inf;Inf], ...
        'target_input_half_v',[0;0],'initial_input_half_v',[0;0], ...
        'mode','off','sense_injection_half_v',zeros(2,1));
    % sense_injection is a deterministic 2xK table, keyed by sample_id modulo K.
    % One column is latched per real write edge; it is not random noise.
    % Its input-referred source adds to Vos sensing, never Qres or ideal VX.
    % Event routing schedules write/hold and Qres polarity; this kernel never re-chops.
    p.ct=struct('net_actual',saved.dac2.net_actual, ...
        'net_nominal',saved.dac2.net_nominal,'net_replica',saved.dac2.net_replica, ...
        'reference_v',double(saved.dac2.reference_v), ...
        'output_parasitic_half_f',double(saved.ra.intrinsic_output_cap_f(:)), ...
        'initial_main_qb_c',double(saved.dac2.initial_floating_charge_b_c(:)), ...
        'initial_replica_qb_c',zeros(2,1),'replica_enabled',true);
    if isscalar(p.ct.output_parasitic_half_f)
        p.ct.output_parasitic_half_f=repmat(p.ct.output_parasitic_half_f,2,1);
    end
    p.ni=struct('cap_mismatch',true,'cinc_kick',true,'az',false, ...
        'ra_noise',false,'az_noise',false,'reference_noise',false, ...
        'nonlinear_ra',false,'replica_delay',false);
    p.scope=['Single closed-loop RA pole; ideal-CM differential behavior; ' ...
        'A-only ideal CT reset, floating B charge retained; zero replica delay. ' ...
        'No transistor, bandwidth/noise identification or full-node KCL claim.'];
end
