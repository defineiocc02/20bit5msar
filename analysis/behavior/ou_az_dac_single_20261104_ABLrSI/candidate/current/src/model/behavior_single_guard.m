function behavior_single_guard(P,prepared)
%BEHAVIOR_SINGLE_GUARD Single-bank 5 MS/s baseline; no implicit ADI selection.
% Preparation and actual RaAdvance setup call this once, never each event.
% Eight FE entries are numerical segments of one bank, not eight converters.
    assert(isstruct(P)&&isscalar(P)&&isfield(P,'front')&&isstruct(P.front)&& ...
        isscalar(P.front)&&isfield(P.front,'single_bank')&& ...
        isscalar(P.front.single_bank)&&isequal(double(P.front.single_bank),1), ...
        'singleBank:only','Apply the single-bank baseline; pool/ADI requires separate authorization.');
    f=P.front;
    assert(isfield(P,'Ts_s')&&isnumeric(P.Ts_s)&&isreal(P.Ts_s)&&isscalar(P.Ts_s)&& ...
        isfinite(P.Ts_s)&&abs(P.Ts_s-200e-9)<1e-18, ...
        'singleBank:rate','This baseline is limited to 5 MS/s.');
    assert(isfield(f,'single_guard_s')&&isnumeric(f.single_guard_s)&&isreal(f.single_guard_s)&& ...
        isscalar(f.single_guard_s)&&isfinite(f.single_guard_s)&&f.single_guard_s>=0, ...
        'singleBank:guard','Guard must be explicit finite nonnegative seconds.');
    assert(isfield(f,'dem_enabled')&&isequal(double(f.dem_enabled),0)&& ...
        isfield(f,'dither_enabled')&&isequal(double(f.dither_enabled),0)&& ...
        isfield(f,'jitter')&&isstruct(f.jitter)&&isscalar(f.jitter)&& ...
        isfield(f.jitter,'enabled')&&isequal(double(f.jitter.enabled),0), ...
        'singleBank:unsupportedNI','Baseline requires DEM, dither and jitter OFF.');
    assert(isfield(P,'transport')&&isstruct(P.transport)&&isfield(P.transport,'enabled')&& ...
        isequal(double(P.transport.enabled),0),'singleBank:transport', ...
        'Baseline uses direct RAW; existing transport bank-parity metadata is not single-bank qualified.');
    for key={'training','cal_cfg','frozen','bank'}
        name=key{1};
        if ~isfield(P,name)
            assert(~prepared,'singleBank:calFlags','Prepared P needs %s.enabled OFF.',name);
            continue;
        end
        q=P.(name);
        assert(isstruct(q)&&isscalar(q)&&isfield(q,'enabled')&& ...
            (isnumeric(q.enabled)||islogical(q.enabled))&&isreal(q.enabled)&& ...
            isscalar(q.enabled)&&isequal(double(q.enabled),0), ...
            'singleBank:calibration','The existing pool calibration/Bank path must remain OFF (%s).',name);
    end
    assert(isfield(P,'digital')&&isstruct(P.digital)&&isfield(P.digital,'calibration_mode')&& ...
        strcmp(P.digital.calibration_mode,'off')&&isfield(P.digital,'dither_enabled')&& ...
        isequal(double(P.digital.dither_enabled),0)&&isfield(P.digital,'d1_bias_v')&& ...
        isnumeric(P.digital.d1_bias_v)&&isreal(P.digital.d1_bias_v)&& ...
        isscalar(P.digital.d1_bias_v)&&isequal(double(P.digital.d1_bias_v),0), ...
        'singleBank:digital','Single bank requires nominal decode, no dither and d1_bias_v=0.');
    assert(isfield(P,'control')&&isfield(P.control,'single_bank')&& ...
        isequal(P.control.single_bank,true),'singleBank:control','Controller bank label must be fixed to zero.');
    assert(isfield(P,'calendar')&&isfield(P,'n_cycles')&&isfield(P,'epoch'), ...
        'singleBank:schedule','Prepared calendar, cycles and epoch required.');
    release=P.calendar(strcmp({P.calendar.type},'release'));
    assert(isscalar(release)&&release.time_s>0&&release.time_s<P.Ts_s&& ...
        f.single_guard_s<P.Ts_s-release.time_s, ...
        'singleBank:acquisition','Release and guard must leave positive acquisition time.');
    assert(isfield(f,'plan_rows')&&isnumeric(f.plan_rows)&&isscalar(f.plan_rows)&& ...
        isfinite(f.plan_rows)&&f.plan_rows>=2&&f.plan_rows<=1e6&& ...
        f.plan_rows==floor(f.plan_rows)&&P.n_cycles+1<=f.plan_rows, ...
        'singleBank:planLength','The plan must cover every next acquisition.');
    ix=(-1:(double(P.n_cycles)-1)).';
    tRelease=ix.*double(P.Ts_s)+release.time_s;
    tOpen=tRelease+double(f.single_guard_s);
    tNext=(ix+1).*double(P.Ts_s);
    assert(all(tOpen<tNext)&&(~f.single_guard_s||all(tOpen>tRelease)), ...
        'singleBank:guardResolution','Guard must be representable between release and next CNV.');
    if ~prepared,return;end
    assert(isfield(f,'plan')&&isa(f.plan,'double')&& ...
        isequal(size(f.plan),[f.plan_rows 8]),'singleBank:plan','Normalized single-bank plan required.');
    for j=1:8
        assert(all(f.plan(:,j)==j),'singleBank:plan','Single-bank plan must use segments 1:8 for every ID.');
    end
    assert(isfield(P,'cal_cfg')&&isfield(P.cal_cfg,'public_cfg')&& ...
        isfield(P.cal_cfg.public_cfg,'pool_schedule')&& ...
        strcmp(P.cal_cfg.public_cfg.pool_schedule,'inactive_single_bank_uncalibrated'), ...
        'singleBank:calLabel','The inactive pool calibration must not claim this bank was calibrated.');
    assert(isfield(f,'C_f')&&isequal(size(f.C_f),[18 38])&& ...
        all(f.C_f(:,1:37)>0,'all')&&all(f.C_f(:,38)==0), ...
        'singleBank:geometry','The 38th bias group must be disconnected.');
    % Prevent the old graph's hard-coded -17Cu from silently corrupting the
    % single-bank decode. Function-only tests intentionally load no model.
    if bdIsLoaded('SarAdc')
        block='SarAdc/EventStep/Fpga/D1CaptureBias';
        assert(strcmp(get_param(block,'Bias'),'DecodeP.d1_bias_v'), ...
            'singleBank:graphBias','The isolated graph must first bind D1CaptureBias to DecodeP.d1_bias_v.');
    end
    assert(isfield(f,'group_C_f')&&isfield(f,'input')&&isfield(P,'input')&& ...
        isfield(P,'xFE0')&&isa(P.xFE0,'double')&&isreal(P.xFE0)&&numel(P.xFE0)==353, ...
        'singleBank:initial','Complete initial source and FE state required.');
    s=behavior_frontend_unpack(P.xFE0,f);
    assert(all(s.B_c(:,3)==0)&&all(s.B_target_c(:,3)==0), ...
        'singleBank:disconnectedCharge','Disconnected initial bias charge and target must already be zero.');
    keys={'offset_v','amplitude_v','frequency_hz','phase_rad'};
    for k=1:numel(keys)
        name=keys{k};
        assert(isfield(P.input,name)&&isfield(f.input,name)&& ...
            isequaln(double(P.input.(name)),double(f.input.(name)))&& ...
            isequaln(double(P.input.(name)),s.input.(name)), ...
            'singleBank:source','Initial Driver, frontend and FE state source must agree.');
    end
    assert(s.has_time&&s.time_s==(-P.Ts_s+release.time_s)&& ...
        all(s.phase(1:8)==1)&&all(s.phase(9:18)==0)&& ...
        all(s.target_id(1:8)==0)&&all(s.target_epoch(1:8)==P.epoch)&& ...
        all(s.acquire_open_s(1:8)==(-P.Ts_s+release.time_s+f.single_guard_s)), ...
        'singleBank:initial','Initial state must reserve the same bank after prior release.');
    assert(isfield(P,'xBK0')&&isfield(f,'Cp_f'),'singleBank:backendInitial', ...
        'The backend initial state and front parasitic capacitances are required.');
    initialBk=behavior_backend_unpack(P.xBK0);ids=f.plan(1,:);
    initialCtop=sum(f.group_C_f(ids,:),'all')+sum(f.Cp_f(ids));
    assert(isequal(typecast(initialBk.command.ctop_f,'uint64'),typecast(initialCtop,'uint64')), ...
        'singleBank:backendInitial','Backend initial Ctop must match the actual single-bank capacitance.');
end
