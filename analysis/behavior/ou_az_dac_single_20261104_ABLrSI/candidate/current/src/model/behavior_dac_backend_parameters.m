function backend=behavior_dac_backend_parameters(P)
%BEHAVIOR_DAC_BACKEND_PARAMETERS Read-only prepared DAC/RA metadata boundary.
% v1 2026-10-27. RaAdvance dialog calls this before native setup/compile/run.
% Return ORIGINAL P.backend; no normalization, rebinding, state, file or RNG.
% Any front tau/schema/public-plan edit requires explicit SAR20('apply',P).
    assert(isstruct(P)&&isscalar(P)&&all(isfield(P,{'front','backend','ni'})), ...
        'behaviorDAC:preparedP','Use the complete explicitly applied P.');
    front=P.front;
    backend=P.backend;
    assert(isstruct(backend)&&isscalar(backend)&&isfield(backend,'dac_coupling')&& ...
        isstruct(backend.dac_coupling)&&isscalar(backend.dac_coupling), ...
        'behaviorDAC:bindingMissing','Missing prepared DAC binding; explicitly apply P before Run.');
    c=backend.dac_coupling;
    assert(all(isfield(c,{'enabled','tau_dac_s','frontend_schema','public_plan'}))&& ...
        all(isfield(front,{'tau_dac_s','schema','plan'})), ...
        'behaviorDAC:bindingMissing','Incomplete DAC binding; explicitly apply P before Run.');
    t=front.tau_dac_s;
    assert(isa(t,'double')&&isreal(t)&&isequal(size(t),[18 1])&&all(~isnan(t))&&all(t>=0), ...
        'behaviorDAC:preparedTau','Expected normalized double tau_dac_s[18x1] seconds.');
    assert(isequal(c.tau_dac_s,t)&&isequal(c.frontend_schema,front.schema)&&isequal(c.public_plan,front.plan), ...
        'behaviorDAC:staleBinding','Front tau/schema/public plan differs from prepared DAC binding; explicitly apply P, do not Run edited workspace P.');
    assert(isscalar(c.enabled)&&isreal(c.enabled)&&ismember(c.enabled,[0 1]), ...
        'behaviorDAC:enabled','Prepared coupling enabled must be one logical flag.');
    assert(c.enabled||all(t==0),'behaviorDAC:uncoupledFinite', ...
        'Nonzero DAC tau (including Inf hold) requires explicitly enabled coupling and apply.');
    expected=logical(c.enabled)&&any(isfinite(t)&t>0);
    assert(isfield(P.ni,'dac_settling')&&isscalar(P.ni.dac_settling)&& ...
        isreal(P.ni.dac_settling)&&ismember(P.ni.dac_settling,[0 1])&& ...
        logical(P.ni.dac_settling)==expected,'behaviorDAC:coverageMismatch', ...
        'Derived NI flag differs: only enabled positive finite tau counts; explicitly apply P.');
    % Compiled model dialogs read the saved ModelWorkspace P, which may have
    % been edited since prepare. Static h/collector cannot run with finite DAC
    % settling or Inf hold; do not auto-disable, repair or infer missing flags.
    if any(t>0)
        for key={'training','cal_cfg','frozen'}
            name=key{1};
            assert(isfield(P,name)&&isstruct(P.(name))&&isscalar(P.(name))&& ...
                isfield(P.(name),'enabled'),'behaviorDAC:calibrationFlags', ...
                'Nonzero DAC tau requires explicit training, cal_cfg and frozen enabled flags; apply a complete P.');
            v=P.(name).enabled;
            assert((isnumeric(v)||islogical(v))&&isreal(v)&&isscalar(v)&& ...
                isfinite(double(v))&&ismember(double(v),[0 1]), ...
                'behaviorDAC:calibrationFlags', ...
                'Nonzero DAC tau requires explicit binary training, cal_cfg and frozen enabled flags; apply a complete P.');
            assert(~logical(v),'behaviorDAC:finiteDACCalibration', ...
                'Nonzero DAC tau requires training.enabled, cal_cfg.enabled and frozen.enabled all OFF; apply a consistent P.');
        end
        assert(isfield(P,'digital')&&isstruct(P.digital)&&isscalar(P.digital)&& ...
            isfield(P.digital,'calibration_mode'),'behaviorDAC:calibrationFlags', ...
            'Nonzero DAC tau requires an explicit digital.calibration_mode; apply a complete P.');
        mode=P.digital.calibration_mode;
        assert((ischar(mode)&&isrow(mode))||(isstring(mode)&&isscalar(mode)), ...
            'behaviorDAC:calibrationFlags', ...
            'Nonzero DAC tau requires digital.calibration_mode as an explicit text scalar.');
        assert(strcmp(mode,'off'),'behaviorDAC:finiteDACCalibration', ...
            'Nonzero DAC tau requires digital.calibration_mode off; apply a consistent P.');
    end
    % Called from the real RaAdvance dialog on the actual model-workspace P.
    % A changed noise profile must never silently inherit old Bank/Frozen h.
    behavior_single_guard(P,true);
    behavior_ra_noise_guard(P);
end
