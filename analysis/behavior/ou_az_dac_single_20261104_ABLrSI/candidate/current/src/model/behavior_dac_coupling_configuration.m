function P=behavior_dac_coupling_configuration(P,enabled)
%BEHAVIOR_DAC_COUPLING_CONFIGURATION Bind immutable FE driving metadata only.
% Candidate call after frontend normalization. Does not enable/modify tau_dac,
% states, graph, event calendar or current prepare's finite-DAC rejection.
% No C truth is copied; public plan preserves the FE reduction order.
    assert(isscalar(enabled)&&isreal(enabled)&&ismember(enabled,[0 1]), ...
        'behaviorDAC:enabled','Use one explicit logical coupling flag.');
    f=P.front;
    t=f.tau_dac_s;
    assert(isnumeric(t)&&isreal(t)&&numel(t)==18&&all(~isnan(t(:)))&&all(t(:)>=0), ...
        'behaviorDAC:tau','Use normalized frontend tau_dac_s[18], nonnegative seconds (Inf holds).');
    assert(enabled||all(t(:)==0),'behaviorDAC:uncoupledFinite', ...
        'Finite frontend DAC tau requires explicit coupling; do not silently run the old constant-Qres backend.');
    assert(ischar(f.schema)&&isnumeric(f.plan)&&isreal(f.plan)&&size(f.plan,2)==8&& ...
        all(isfinite(f.plan(:)))&&all(f.plan(:)>=1&f.plan(:)<=18&f.plan(:)==floor(f.plan(:))), ...
        'behaviorDAC:frontMetadata','Need normalized frontend schema and public eight-slice plan.');
    if enabled&&any(t(:)>0)
        assert(isinf(P.backend.ra.slew_v_per_s), ...
            'behaviorDAC:slewUnsupported','Finite-DAC analytic coupling currently requires linear RA (slew=Inf).');
    end
    P.backend.dac_coupling=struct('enabled',logical(enabled),'tau_dac_s',double(t(:)), ...
        'frontend_schema',f.schema,'public_plan',double(f.plan));
    % New OU+AZ/DAC mode is limited to the actual fixed one-bank capacitance.
    % This is immutable parameter metadata, not a second stored analog state.
    if P.backend.ni.ra_noise&&(P.backend.ni.az||any(t(:)>0))
        assert(isfield(f,'single_bank')&&isequal(f.single_bank,true)&& ...
            all(isfinite(t(:)))&&isfield(f,'group_C_f')&&isfield(f,'Cp_f')&& ...
            size(f.plan,2)==8&&all(f.plan==repmat(1:8,size(f.plan,1),1),'all'), ...
            'sar20RA:singleBankLinear','Combined OU requires fixed single-bank plan and finite DAC taus.');
        ids=f.plan(1,:);
        P.backend.dac_coupling.fixed_single_bank_ctop_f= ...
            sum(f.group_C_f(ids,:),'all')+sum(f.Cp_f(ids));
    end
end
