function x = behavior_frontend_pack(s)
%BEHAVIOR_FRONTEND_PACK Convert named frontend state to its UnitDelay vector.
%Version: v1 (2026-10-27). Caller: frontend model initializer/commit adapter.
%Input s from frontend init/step; output x[353,1] double, preserving mixed SI units:
%time [s], source [V,Hz,rad], charges [C], voltages [V], unitless tags/flags.
%B matrices use column-major order: all signal, all tail, all bias entries.
%Append: 318:335 actual aperture [s], 336:353 acquire_open [s].
%Legacy 1:317 unchanged. Runtime reset invalidates capture tags, retains time metadata.
%Pure ABI conversion; no state advancement, reset, parameter regeneration or RNG.
%The vector is module-specific; it does not reuse the old full-node state ABI.
    x=[double(s.time_s);double(s.has_time); ...
        double(s.input.offset_v);double(s.input.amplitude_v); ...
        double(s.input.frequency_hz);double(s.input.phase_rad); ...
        double(s.phase(:));double(s.B_c(:));double(s.B_target_c(:)); ...
        double(s.q_initial_c(:));double(s.v_capture_v(:)); ...
        double(s.target_id(:));double(s.target_epoch(:)); ...
        double(s.capture_id(:));double(s.capture_epoch(:)); ...
        double(s.capture_valid(:));double(s.aperture_s(:)); ...
        double(s.active_id);double(s.active_epoch);double(s.d1_code); ...
        double(s.has_dac_command);double(s.event_count); ...
        double(s.dem_shift(:));double(s.dither_input_v(:)); ...
        double(s.actual_aperture_s(:));double(s.acquire_open_s(:))];
    assert(isequal(size(x),[353 1]),'behaviorFE:packWidth','Frontend state ABI must contain 353 doubles.');
end
