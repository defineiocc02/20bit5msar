function s=behavior_backend_unpack(v)
%BEHAVIOR_BACKEND_UNPACK Current AZ v2 fixed 48-word layout; see pack.
% Numeric UnitDelay owns the only state. Epoch invalidation belongs to step,
% not this pure conversion. Analog AZ half voltages remain at legacy words3:4.
% Metadata units: flags 38/42; IDs/count36:40,43:45; age/elapsed41/48 [s];
% held sensing source46:47 [V]. RST_SIG retains AZ; epoch revokes service tags
% without erasing analog storage. See pack for all48 named offsets.
    assert(isa(v,'double')&&isreal(v)&&isvector(v)&&numel(v)==48&&all(isfinite(v(:))), ...
        'behavior:unpack','AZ backend state requires 48 finite doubles.');
    v=v(:);
    assert(all(ismember(v(14:32),[-1 0 1]))&& ...
        all(ismember(v([33:35 38 42]),[0 1])), ...
        'behavior:unpackFlags','Invalid physical signs or AZ booleans.');
    tags=v([36:37 39:40 43:45]);
    assert(all(tags==floor(tags))&&v(36)>=-1&&v(37)>=0&& ...
        all(v([39 40 44 45])>=-1)&&v(43)>=0&&v(41)>=0&&v(48)>=0, ...
        'behavior:unpackTags','Invalid AZ service tags, count or time.');
    c=struct('qres_c',v(12),'ctop_f',v(13),'d2_signs',v(14:25), ...
        'ta_signs',v(26:32),'ra_on',logical(v(33)), ...
        'az_on',logical(v(34)),'reset',logical(v(35)), ...
        'sample_id',v(36),'epoch',v(37));
    a=struct('valid',logical(v(38)),'pair_id',v(39),'epoch',v(40), ...
        'age_s',v(41),'write_active',logical(v(42)),'write_count',v(43), ...
        'last_write_sample_id',v(44),'last_service_sample_id',v(45), ...
        'write_source_half_v',v(46:47),'write_elapsed_s',v(48));
    s=struct('schema','behavior-backend-state/v2','time_s',v(1), ...
        'units','time_s [s], vx_v [V differential], AZ [V input referred], qB [C]', ...
        'vx_v',v(2),'az_input_half_v',v(3:4),'ct_reset_vx_v',v(5), ...
        'main_qb_c',v(6:7),'replica_qb_c',v(8:9), ...
        'previous_switch_charge_c',v(10:11),'command',c,'az',a);
end
