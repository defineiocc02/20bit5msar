function protocol=make_training_protocol()
%MAKE_TRAINING_PROTOCOL v1 2026-10-27. Predeclared bench sources and gates.
% No model/run/data input. These are external calibrated-source assumptions,
% not estimates from ADC outputs. Persist this value before any training data.
    fs=5e6;amplitude=3.650563842595822;
    train=struct('offset_v',0,'amplitude_v',amplitude,'frequency_hz',37*fs/2048,'phase_rad',.731);
    holdout=struct('offset_v',0,'amplitude_v',amplitude,'frequency_hz',23*fs/1024,'phase_rad',1.217);
    protocol=struct('schema','sar20-training-protocol/v1', ...
        'train',struct('records',2048,'first_id',4,'epoch',1,'source',train), ...
        'holdout',struct('records',1024,'first_id',4,'epoch',2,'source',holdout), ...
        'sample_period_s',1/fs,'public_plan_rows',2056, ...
        'chip_seed',20261028,'sigma_unit_fraction',.001,'DEM',true,'dither',true, ...
        'source_assumption','Ideal independently declared calibrated source, zero reference uncertainty; not a hardware measurement', ...
        'thresholds',struct('relative_singular_cutoff',1e-10,'maximum_condition_number',1e8, ...
            'training_rms_limit_v',7.8125e-6,'holdout_rms_limit_v',7.8125e-6,'holdout_max_abs_limit_v',31.25e-6), ...
        'holdout_policy','Do not run/read holdout until training gates pass; no selection or retuning using holdout', ...
        'fit_policy','Full684/no regularization/no nominal fill/positive h and denominator/full DEM coverage', ...
        'code_output_during_collection','Nominal unchanged; candidate is not automatically frozen or activated');
end
