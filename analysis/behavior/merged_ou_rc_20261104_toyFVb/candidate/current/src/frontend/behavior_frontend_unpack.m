function s = behavior_frontend_unpack(x,p)
%BEHAVIOR_FRONTEND_UNPACK Restore named state from the frontend UnitDelay vector.
%Version: v1 (2026-10-27). Caller: frontend advance/commit adapter.
%Inputs x[353] real numeric words and normalized p from frontend_init; output s.
%Units/offset order match behavior_frontend_pack: s/V/Hz/rad/C plus tags/flags.
%Append actual aperture 318:335 [s], acquire_open 336:353 [s]; legacy prefix unchanged.
%Metadata retained on runtime reset; validity comes from capture_valid/tags.
%Pure ABI inverse; no initialization/reset, parameter or plan regeneration, or RNG.
%Model equations are evaluated by frontend_step, not by this conversion.
    assert(isnumeric(x)&&isreal(x)&&numel(x)==353, ...
        'behaviorFE:unpackWidth','Expected 353-double frontend UnitDelay state.');
    x=double(x(:));
    s=struct('schema',p.schema,'time_s',x(1),'has_time',logical(x(2)), ...
        'input',struct('offset_v',x(3),'amplitude_v',x(4),'frequency_hz',x(5),'phase_rad',x(6)), ...
        'phase',x(7:24),'B_c',reshape(x(25:78),18,3), ...
        'B_target_c',reshape(x(79:132),18,3), ...
        'q_initial_c',x(133:150),'v_capture_v',x(151:168), ...
        'target_id',x(169:186),'target_epoch',x(187:204), ...
        'capture_id',x(205:222),'capture_epoch',x(223:240), ...
        'capture_valid',logical(x(241:258)),'aperture_s',x(259:276), ...
        'active_id',x(277),'active_epoch',x(278),'d1_code',x(279), ...
        'has_dac_command',logical(x(280)),'event_count',x(281), ...
        'dem_shift',x(282:299),'dither_input_v',x(300:317), ...
        'actual_aperture_s',x(318:335),'acquire_open_s',x(336:353));
end
