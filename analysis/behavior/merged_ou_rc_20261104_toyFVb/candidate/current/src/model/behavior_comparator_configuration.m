function P=behavior_comparator_configuration(P,mode)
%BEHAVIOR_COMPARATOR_CONFIGURATION Validate optional bounded comparator profile.
% 'derive' operates on explicit apply; 'check' inspects actual dialog P.
% A missing profile is the legacy exact OFF path and does not change P shape.
% Active CMP with OU is limited to the bound linear single-bank case below;
% training/Frozen/Bank remain OFF. Comparator delay/invalid/late are absent.
    if nargin<2,mode='check';end
    assert(any(strcmp(mode,{'derive','check'})),'sar20Cmp:mode','Use derive or check.');
    assert(isstruct(P)&&isscalar(P)&&isfield(P,'control')&&isstruct(P.control)&& ...
        isscalar(P.control),'sar20Cmp:P','Require explicit P.control.');
    if ~isfield(P.control,'comparator')
        % A removed profile must not leave a false noise-coverage claim. Older
        % configs without this label remain a legacy OFF path.
        if isfield(P,'ni')&&isstruct(P.ni)&&isscalar(P.ni)
            if isfield(P.ni,'comparator_noise')
                assert(binary(P.ni.comparator_noise)&&~logical(P.ni.comparator_noise), ...
                    'sar20Cmp:coverage','Missing comparator profile cannot report enabled noise.');
            end
            if isfield(P.ni,'comparator_noise_scope')
                none=struct('sar1_fine',false,'sar2_and_tracking',false,'flash_preconvert',false);
                assert(isequaln(P.ni.comparator_noise_scope,none), ...
                    'sar20Cmp:scope','Missing comparator profile cannot claim comparator coverage.');
            end
        end
        return;
    end
    c=P.control.comparator;
    names={'enabled';'sar1_offset_v';'sar1_noise_rms_v';'sar2_offset_v'; ...
        'sar2_noise_rms_v';'seed_u64';'tie_decision'};
    assert(isstruct(c)&&isscalar(c)&&isequal(sort(fieldnames(c)),sort(names)), ...
        'sar20Cmp:config','Comparator profile must contain exactly the declared fields.');
    assert(binary(c.enabled)&&binary(c.tie_decision),'sar20Cmp:flag','Flags must be 0/1.');
    for f={'sar1_offset_v','sar1_noise_rms_v','sar2_offset_v','sar2_noise_rms_v'}
        v=c.(f{1});assert(isa(v,'double')&&isreal(v)&&isscalar(v)&&isfinite(v), ...
            'sar20Cmp:scale','Comparator offset/noise values must be finite double V.');
    end
    assert(c.sar1_noise_rms_v>=0&&c.sar2_noise_rms_v>=0, ...
        'sar20Cmp:noise','Comparator noise RMS cannot be negative.');
    assert(isa(c.seed_u64,'uint64')&&isscalar(c.seed_u64), ...
        'sar20Cmp:seed','Comparator seed must be uint64 scalar.');
    assert(isfield(P,'ni')&&isstruct(P.ni)&&isscalar(P.ni), ...
        'sar20Cmp:coverage','P.ni must be an explicit scalar coverage struct.');
    % Reapply may add a missing label; check never fabricates one. A present
    % malformed label is rejected even during derive, matching NI contracts.
    if strcmp(mode,'derive')&&~isfield(P.ni,'comparator_noise')
        P.ni.comparator_noise=false;
    end
    assert(isfield(P.ni,'comparator_noise')&&binary(P.ni.comparator_noise), ...
        'sar20Cmp:coverage','P.ni.comparator_noise must be an explicit binary flag.');
    fine=logical(c.enabled)&&c.sar1_noise_rms_v>0;
    sar2=logical(c.enabled)&&c.sar2_noise_rms_v>0;
    noise=fine||sar2;
    % This candidate acts on five SAR1 fine comparisons and SAR2/TA only.
    % The six-bit Flash preconverter never receives this noise model.
    scope=struct('sar1_fine',logical(fine),'sar2_and_tracking',logical(sar2), ...
        'flash_preconvert',false);
    active=logical(c.enabled)&&(noise||c.sar1_offset_v~=0||c.sar2_offset_v~=0);
    if strcmp(mode,'derive')
        P.ni.comparator_noise=logical(noise);
        P.ni.comparator_noise_scope=scope;
    else
        assert(logical(P.ni.comparator_noise)==logical(noise), ...
            'sar20Cmp:coverage','Comparator noise coverage is stale; apply P.');
        assert(isfield(P.ni,'comparator_noise_scope')&&isequaln(P.ni.comparator_noise_scope,scope), ...
            'sar20Cmp:scope','Comparator channel/Flash coverage is stale; apply P.');
    end
    if active
        assert(isfield(P,'backend')&&isstruct(P.backend)&&isfield(P.backend,'ni')&& ...
            isstruct(P.backend.ni)&&isfield(P.backend.ni,'ra_noise')&& ...
            binary(P.backend.ni.ra_noise), ...
            'sar20Cmp:raNoiseBinding','Require the actual binary RA OU enable.');
        for key={'training','cal_cfg','frozen','bank'}
            name=key{1};
            assert(isfield(P,name)&&isstruct(P.(name))&&isscalar(P.(name))&& ...
                isfield(P.(name),'enabled')&&binary(P.(name).enabled), ...
                'sar20Cmp:qualificationFlags','Require explicit %s.enabled.',name);
            assert(~logical(P.(name).enabled),'sar20Cmp:unqualifiedCalibration', ...
                'Nonzero comparator stress requires %s.enabled OFF.',name);
        end
        % The event-key index is meaningful only under the exact fixed calendar.
        % Check the ACTUAL P at model setup, not only the values once prepared.
        validate_active_calendar(P);
        if P.backend.ni.ra_noise
            validate_joint_ra_binding(P);
        end
    end
end
function validate_active_calendar(P)
% No regeneration or mutation of P; rederive only for this comparison.
    fields={'calendar','adc_groups','groups','transport','schedule', ...
        'Ts_s','N','first_id','n_cycles','stop_time_s'};
    assert(all(isfield(P,fields))&&isstruct(P.transport)&&isscalar(P.transport)&& ...
        isfield(P.transport,'enabled')&&binary(P.transport.enabled)&& ...
        isstruct(P.schedule)&&isscalar(P.schedule)&& ...
        all(isfield(P.schedule,{'sample_period_s','n_cycles','groups','stop_time_s'}))&& ...
        isfield(P.control,'sample_period_s'), ...
        'sar20Cmp:calendarContract','Nonzero comparator stress requires complete saved calendar/schedule.');
    % This overlay is limited to the single-bank M8 baseline. It does not
    % qualify pool, runtime transport, or a separately prepared M1 profile.
    assert(isfield(P,'front')&&isstruct(P.front)&&isscalar(P.front)&&isfield(P.front,'single_bank')&& ...
        isequal(P.front.single_bank,true)&&isfield(P.control,'single_bank')&& ...
        isequal(P.control.single_bank,true)&&~logical(P.transport.enabled), ...
        'sar20Cmp:singleOnly','Active comparator profile requires the direct single-bank baseline.');
    assert((~isfield(P.control,'tracking_count')||isequal(double(P.control.tracking_count),8))&& ...
        isfield(P,'digital')&&isstruct(P.digital)&&isscalar(P.digital)&&isfield(P.digital,'tracking_mode')&& ...
        strcmp(P.digital.tracking_mode,'finite_sinc2')&& ...
        (~isfield(P.digital,'tracking_count')||isequal(double(P.digital.tracking_count),8)), ...
        'sar20Cmp:m8Only','Active comparator profile supports only M8.');
    assert(isstruct(P.calendar)&&all(isfield(P.calendar,{'type','index','bit'})), ...
        'sar20Cmp:calendarContract','Actual M8 calendar is required.');
    types={P.calendar.type};
    ta=P.calendar(strcmp(types,'ta_compare'));fb=P.calendar(strcmp(types,'ta_feedback'));
    assert(numel(ta)==8&&isequal([ta.index],0:7)&&isequal([ta.bit],7:-1:0)&& ...
        numel(fb)==7&&isequal([fb.index],0:6)&&isequal([fb.bit],7:-1:1), ...
        'sar20Cmp:m8Only','M8 requires eight comparisons and seven physical updates.');
    for key={'Ts_s','N','first_id','n_cycles','stop_time_s'}
        v=P.(key{1});
        assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v), ...
            'sar20Cmp:calendarContract','Invalid scalar schedule field %s.',key{1});
    end
    v=P.control.sample_period_s;
    assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v)&& ...
        abs(P.Ts_s-200e-9)<1e-18&&P.N>=1&&P.N==floor(P.N)&&P.first_id>=0&& ...
        P.first_id==floor(P.first_id)&&P.n_cycles==floor(P.n_cycles)&& ...
        v==P.Ts_s, ...
        'sar20Cmp:calendarContract','Invalid period, sample counts or saved time metadata.');
    on=logical(P.transport.enabled);
    calendar=behavior_calendar(P.control);
    adc=behavior_event_groups(calendar,false);
    groups=behavior_event_groups(calendar,on);
    assert(numel(adc)==48&&numel(groups)==48+double(on)&& ...
        isequaln(P.calendar,calendar)&&isequaln(P.adc_groups,adc)&& ...
        isequaln(P.groups,groups)&&isequaln(P.schedule.groups,groups), ...
        'sar20Cmp:calendarContract','Actual event groups differ from the fixed canonical calendar.');
    expectedCycles=P.first_id+P.N+2*double(on);
    expectedStop=(expectedCycles-1)*P.Ts_s+groups(end).time_s;
    assert(P.n_cycles==expectedCycles&&P.stop_time_s==expectedStop&& ...
        isequaln(P.schedule.sample_period_s,P.Ts_s)&& ...
        isequaln(P.schedule.n_cycles,P.n_cycles)&& ...
        isequaln(P.schedule.stop_time_s,P.stop_time_s), ...
        'sar20Cmp:calendarContract','Actual scheduler period, cycle count or stop differs.');
end
function validate_joint_ra_binding(P)
% No state or profile mutation: verify the actual fixed-Ctop single-bank RA.
% The full coverage check still belongs to behavior_ra_noise_guard/RaAdvance.
    behavior_ra_noise_validate_backend(P.backend);
    assert(isfield(P.backend,'dac_coupling')&&isstruct(P.backend.dac_coupling)&& ...
        isscalar(P.backend.dac_coupling)&& ...
        all(isfield(P.backend.dac_coupling,{'fixed_single_bank_ctop_f','tau_dac_s','public_plan','frontend_schema'}))&& ...
        isfield(P,'front')&&isstruct(P.front)&&isscalar(P.front)&& ...
        all(isfield(P.front,{'plan','tau_dac_s','schema','group_C_f','Cp_f'})), ...
        'sar20Cmp:jointBinding','OU plus comparator requires prepared fixed-Ctop FE metadata.');
    f=P.front;c=P.backend.dac_coupling;
    assert(isequal(c.public_plan,f.plan)&&isequal(c.tau_dac_s,f.tau_dac_s)&& ...
        isequal(c.frontend_schema,f.schema),'sar20Cmp:jointBinding', ...
        'OU plus comparator frontend plan/tau/schema differs from the applied binding.');
    behavior_single_guard(P,true);
    ids=f.plan(1,:);
    actual=sum(f.group_C_f(ids,:),'all')+sum(f.Cp_f(ids));
    assert(isequal(typecast(actual,'uint64'),typecast(c.fixed_single_bank_ctop_f,'uint64')), ...
        'sar20Cmp:jointBinding','OU plus comparator fixed Ctop differs from actual FE.');
end
function b=binary(v)
    b=(isnumeric(v)||islogical(v))&&isreal(v)&&isscalar(v)&& ...
        isfinite(double(v))&&ismember(double(v),[0 1]);
end
