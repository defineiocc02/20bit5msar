function P=behavior_ra_noise_guard(P,mode)
%BEHAVIOR_RA_NOISE_GUARD Forbid reuse of unqualified ON noise profiles.
%
%   P = behavior_ra_noise_guard(P)          % check
%   P = behavior_ra_noise_guard(P, 'derive')% check and record the coverage map
%
% Called on the actual prepared P and by the actual RaAdvance dialog.
%
% TWO MODES
%   check    assert the coverage flags already present in P are consistent
%   derive   recompute the coverage map from P and store it
%
% OU OFF/ON both derive or check the physical coverage summary. An OFF P need
% not contain a ra_noise coverage field; existing false fields are preserved.
% ON sigma=0 remains a diagnostic and records coverage=false. Old prepared P
% with stale/missing coverage must be reapplied or explicitly corrected.
%
% WHY THIS EXISTS
%   An ON profile is only meaningful when the specific non-idealities it claims
%   to cover are actually the ones switched on. The guard re-derives the calendar
%   and every M8 structure from P and compares, so a stale or hand-edited
%   schedule is rejected rather than silently treated as qualified.
%
% No analog truth ever reaches the decoder through this function.
    if nargin<2,mode='check';end
    assert(ischar(mode)&&isrow(mode)&&any(strcmp(mode,{'check','derive'})), ...
        'sar20RA:coverageMode','Use check or derive.');
    assert(isstruct(P)&&isscalar(P)&&isfield(P,'backend')&&isstruct(P.backend)&& ...
        isscalar(P.backend)&&isfield(P.backend,'ni')&&isstruct(P.backend.ni)&& ...
        isscalar(P.backend.ni)&&isfield(P.backend.ni,'ra_noise')&&binary(P.backend.ni.ra_noise), ...
        'sar20RA:flag','Actual P needs one binary backend.ni.ra_noise flag.');
    on=logical(P.backend.ni.ra_noise);
    assert(isfield(P,'ni')&&isstruct(P.ni)&&isscalar(P.ni), ...
        'sar20RA:coverage','Actual P needs its existing NI coverage summary.');
    % The new zero-amplitude ordinary projection must not become a route to
    % enable a collector, Frozen cache or Bank by a later workspace edit.
    assert(isfield(P,'front')&&isstruct(P.front)&&isscalar(P.front)&& ...
        all(isfield(P.front,{'dither_enabled','dither_input_amplitude_v','dither_seed'}))&& ...
        binary(P.front.dither_enabled)&&isnumeric(P.front.dither_input_amplitude_v)&& ...
        isreal(P.front.dither_input_amplitude_v)&&isscalar(P.front.dither_input_amplitude_v)&& ...
        isfinite(P.front.dither_input_amplitude_v)&&P.front.dither_input_amplitude_v>=0, ...
        'calConfig:zeroDitherFront','Complete physical dither fields required.');
    % Mirror the public apply-time dither join on the real model-workspace P.
    % This also catches a zero-to-nonzero single-side edit after preparation.
    assert(isfield(P,'digital')&&isstruct(P.digital)&&isscalar(P.digital)&& ...
        all(isfield(P.digital,{'dither_enabled','dither_seed','dither_amplitude_v'}))&& ...
        binary(P.digital.dither_enabled)&& ...
        isnumeric(P.front.dither_seed)&&isreal(P.front.dither_seed)&&isscalar(P.front.dither_seed)&& ...
        isfinite(P.front.dither_seed)&&P.front.dither_seed>=0&&P.front.dither_seed<=2^32-1&& ...
        P.front.dither_seed==floor(P.front.dither_seed)&& ...
        isnumeric(P.digital.dither_seed)&&isreal(P.digital.dither_seed)&&isscalar(P.digital.dither_seed)&& ...
        isfinite(P.digital.dither_seed)&&P.digital.dither_seed>=0&&P.digital.dither_seed<=2^32-1&& ...
        P.digital.dither_seed==floor(P.digital.dither_seed)&& ...
        isnumeric(P.digital.dither_amplitude_v)&&isreal(P.digital.dither_amplitude_v)&& ...
        isscalar(P.digital.dither_amplitude_v)&&isfinite(P.digital.dither_amplitude_v)&& ...
        P.digital.dither_amplitude_v>=0&& ...
        double(P.front.dither_enabled)==double(P.digital.dither_enabled)&& ...
        double(P.front.dither_seed)==double(P.digital.dither_seed)&& ...
        double(P.front.dither_input_amplitude_v)==double(P.digital.dither_amplitude_v), ...
        'calConfig:ditherJoin','Applied frontend/digital dither enable, seed and amplitude must agree.');
    if P.front.dither_enabled&&P.front.dither_input_amplitude_v==0
        for field={'training','cal_cfg','frozen','bank'}
            name=field{1};
            assert(isfield(P,name)&&isstruct(P.(name))&&isscalar(P.(name))&& ...
                isfield(P.(name),'enabled')&&binary(P.(name).enabled)&&~P.(name).enabled, ...
                'calConfig:zeroDitherQualification','Zero dither is ordinary-only; %s must be off.',name);
        end
    end
    % Optional comparator configuration must be checked/derived on actual P.
    hasComparator=isfield(P,'control')&&isstruct(P.control)&&isscalar(P.control)&& ...
        isfield(P.control,'comparator');
    if ~hasComparator&&isfield(P.ni,'comparator_noise')
        assert(binary(P.ni.comparator_noise)&&~logical(P.ni.comparator_noise), ...
            'sar20RA:comparatorNoise','Missing comparator model cannot claim noise coverage.');
    end
    if isfield(P,'control')&&isstruct(P.control)&&isscalar(P.control)
        P=behavior_comparator_configuration(P,mode);
    elseif isfield(P.ni,'comparator_noise_scope')
        error('sar20Cmp:scope','Comparator coverage requires an explicit control structure.');
    end
    if ~on
        if isfield(P.ni,'ra_noise')
            assert(binary(P.ni.ra_noise)&&~logical(P.ni.ra_noise), ...
                'sar20RA:coverage','OFF cannot report ON noise coverage.');
        end
        P=validate_coverage(P,mode);
        % Unsupported labels cannot be promoted to coverage in OFF profiles.
        if isfield(P.ni,'reference_recovery')
            assert(binary(P.ni.reference_recovery)&&~logical(P.ni.reference_recovery), ...
                'sar20RA:referenceRecovery','Reference recovery is not implemented.');
        end
        return;
    end
    behavior_ra_noise_validate_backend(P.backend);
    assert(isfield(P.ni,'az')&&binary(P.ni.az)&& ...
        logical(P.ni.az)==logical(P.backend.ni.az), ...
        'sar20RA:coverageAZ','P.ni.az must match actual backend AZ enable.');
    validate_control_and_m8(P);
    validate_transport_binding(P);
    P=validate_coverage(P,mode);
    assert(isfield(P.ni,'ra_noise')&&binary(P.ni.ra_noise)&& ...
        logical(P.ni.ra_noise)==(P.backend.ra_noise.sigma_vx_rms>0), ...
        'sar20RA:coverage','Coverage must reflect positive output noise RMS.');
    for field={'training','cal_cfg','frozen','bank'}
        name=field{1};
        assert(isfield(P,name)&&isstruct(P.(name))&&isscalar(P.(name))&& ...
            isfield(P.(name),'enabled')&&binary(P.(name).enabled), ...
            'sar20RA:qualificationFlags','ON requires explicit %s.enabled.',name);
        assert(~logical(P.(name).enabled),'sar20RA:unqualifiedCalibration', ...
            'RA noise ON cannot reuse training, Frozen or Bank qualification (%s).',name);
    end
    % Reference recovery is not implemented; a stale true label must not be
    % reported as realized coverage merely because RA noise is enabled.
    if isfield(P.ni,'reference_recovery')
        assert(binary(P.ni.reference_recovery)&&~logical(P.ni.reference_recovery), ...
            'sar20RA:referenceRecovery','RA OU profile cannot claim reference-recovery coverage.');
    end
    % The comparator configuration checked above owns fine/SAR2 coverage.
    % The separate six-bit Flash coarse-noise source remains unimplemented.
    assert(isfield(P.ni,'comparator_noise')&&binary(P.ni.comparator_noise), ...
        'sar20RA:comparatorNoise','Explicit comparator noise coverage is required.');
    assert(isfield(P,'control')&&isstruct(P.control)&&isscalar(P.control)&& ...
        isfield(P.control,'sar1')&&isstruct(P.control.sar1)&&isscalar(P.control.sar1)&& ...
        isfield(P.control.sar1,'coarse_noise_rms_v'), ...
        'sar20RA:comparatorNoise','Require explicit SAR1 coarse noise parameter.');
    cn=P.control.sar1.coarse_noise_rms_v;
    assert(isa(cn,'double')&&isreal(cn)&&isscalar(cn)&&isfinite(cn)&&cn==0, ...
        'sar20RA:comparatorNoise','RA OU profile requires coarse noise RMS exactly zero.');
    assert(isfield(P,'digital')&&isstruct(P.digital)&&isscalar(P.digital)&& ...
        isfield(P.digital,'calibration_mode')&& ...
        (ischar(P.digital.calibration_mode)||isstring(P.digital.calibration_mode))&& ...
        isscalar(string(P.digital.calibration_mode))&&strcmp(P.digital.calibration_mode,'off'), ...
        'sar20RA:unqualifiedCalibration','RA noise ON requires digital calibration mode OFF.');
    assert(isfield(P,'front')&&isstruct(P.front)&&isscalar(P.front)&& ...
        isfield(P.front,'tau_dac_s')&&isa(P.front.tau_dac_s,'double')&& ...
        isreal(P.front.tau_dac_s)&&isequal(size(P.front.tau_dac_s),[18 1])&& ...
        all(isfinite(P.front.tau_dac_s(:))&P.front.tau_dac_s(:)>=0)&& ...
        isequal(P.front.tau_dac_s,P.backend.dac_coupling.tau_dac_s), ...
        'sar20RA:finiteDAC','RA noise ON needs finite front DAC taus equal to the prepared binding.');
    if P.backend.ni.az||any(P.front.tau_dac_s(:)>0)|| ...
            isfield(P.backend.dac_coupling,'fixed_single_bank_ctop_f')
        f=P.front;c=P.backend.dac_coupling;
        assert(isfield(f,'single_bank')&&isequal(f.single_bank,true)&& ...
            isfield(f,'plan')&&isequal(c.public_plan,f.plan)&& ...
            isfield(f,'schema')&&isequal(c.frontend_schema,f.schema)&& ...
            isfield(f,'group_C_f')&&isfield(f,'Cp_f'), ...
            'sar20RA:singleBankLinear','Joint OU metadata must remain bound to the actual single bank.');
        ids=f.plan(1,:);
        actualCtop=sum(f.group_C_f(ids,:),'all')+sum(f.Cp_f(ids));
        assert(isequal(typecast(c.fixed_single_bank_ctop_f,'uint64'),typecast(actualCtop,'uint64')), ...
            'sar20RA:singleBankCtop','The joint OU Ctop binding is stale; reapply the actual frontend.');
    end
end

function validate_control_and_m8(P)
% These are actual ON control values, including direct workspace edits. Inf
% limit explicitly disables this model's overrange test; it is not coverage.
    assert(isfield(P,'control')&&isstruct(P.control)&&isscalar(P.control)&& ...
        isfield(P.control,'sar1')&&isstruct(P.control.sar1)&&isscalar(P.control.sar1)&& ...
        all(isfield(P.control.sar1,{'delta_v','coarse_offset_v'}))&& ...
        isfield(P.control,'sar2')&&isstruct(P.control.sar2)&&isscalar(P.control.sar2)&& ...
        isfield(P.control.sar2,'limit_v'),'sar20RA:control','Explicit SAR control values required.');
    a=P.control.sar1.delta_v;
    b=P.control.sar1.coarse_offset_v;
    c=P.control.sar2.limit_v;
    assert(isa(a,'double')&&isreal(a)&&isscalar(a)&&isfinite(a)&&a>0&& ...
        isa(b,'double')&&isreal(b)&&isscalar(b)&&isfinite(b)&& ...
        isa(c,'double')&&isreal(c)&&isscalar(c)&&~isnan(c)&&c>0, ...
        'sar20RA:control','Require positive finite delta, finite offset, positive finite/+Inf limit.');
    assert(isfield(P,'calendar')&&isstruct(P.calendar)&&all(isfield(P.calendar,{'type','index','bit'}))&& ...
        isfield(P,'adc_groups')&&isstruct(P.adc_groups)&&isfield(P,'groups')&&isstruct(P.groups)&& ...
        isfield(P,'transport')&&isstruct(P.transport)&&isscalar(P.transport)&& ...
        isfield(P.transport,'enabled')&&binary(P.transport.enabled), ...
        'sar20RA:m8Calendar','Prepared fixed M8 calendar/groups/transport are required.');
    assert(isfield(P,'digital')&&isstruct(P.digital)&&isscalar(P.digital)&& ...
        isfield(P.digital,'tracking_mode')&&strcmp(P.digital.tracking_mode,'finite_sinc2'), ...
        'sar20RA:m8Digital','OU ON requires actual finite_sinc2 tracking mode.');
    % The M8 tracking combine requires exactly eight ordered TA decisions and
    % seven feedback events; their index/bit order is asserted below.
    types={P.calendar.type};
    ta=P.calendar(strcmp(types,'ta_compare'));
    fb=P.calendar(strcmp(types,'ta_feedback'));
    assert(numel(ta)==8&&isequal([ta.index],0:7)&&isequal([ta.bit],7:-1:0)&& ...
        numel(fb)==7&&isequal([fb.index],0:6)&&isequal([fb.bit],7:-1:1), ...
        'sar20RA:m8Calendar','OU ON requires eight ordered TA decisions and seven feedback events.');
    % Re-derive the whole calendar from the control values and compare. Anything
    % that does not match is a stale or hand-edited schedule, not a valid one.
    expected=behavior_calendar(P.control);
    groups=behavior_event_groups(expected,false);
    allGroups=behavior_event_groups(expected,logical(P.transport.enabled));
    assert(isequaln(P.calendar,expected)&&isequaln(P.adc_groups,groups)&& ...
        numel(P.adc_groups)==48&&numel(P.groups)==48+double(P.transport.enabled)&& ...
        isequaln(P.groups,allGroups)&&isequaln(P.groups(1:48),P.adc_groups), ...
        'sar20RA:m8Calendar','Actual saved ADC calendar/groups differ from the fixed M8 scheduler.');
end

function validate_transport_binding(P)
% Reuse the actual existing transport schedule/flush/stop/EN contract on a
% local copy; do not write it back or silently normalize direct workspace edits.
    assert(all(isfield(P,{'Ts_s','N','first_id','epoch','n_cycles','stop_time_s','schedule','xTX0'}))&& ...
        isstruct(P.schedule)&&isscalar(P.schedule)&& ...
        all(isfield(P.schedule,{'sample_period_s','n_cycles','groups','stop_time_s'})), ...
        'sar20RA:transportBinding','Complete saved schedule/cycles/stop and transport IC are required.');
    assert(isfield(P.transport,'adc_group_count')&&P.transport.adc_group_count==48&& ...
        isfield(P.transport,'flush_cycles')&& ...
        P.transport.flush_cycles==2*double(P.transport.enabled), ...
        'sar20RA:transportBinding','ADC group count/flush metadata differs.');
    checked=behavior_transport_configuration(P);
    assert(isequaln(checked.transport,P.transport)&&isequaln(checked.xTX0,P.xTX0), ...
        'sar20RA:transportBinding','Saved transport config/IC differs from actual derived contract.');
end

function P=validate_coverage(P,mode)
% Coverage here reflects actual enabled finite effects. Parasitic is the
% existing NARROW front-Cp/RA-output-load indicator, not full CT parasitics.
    for key={'ra_finite_gain','ra_finite_bandwidth','sample_settling','sample_ktc','jitter','cap_mismatch','parasitic'}
        name=key{1};
        % Reapply can populate an older missing summary; direct check cannot.
        % A present malformed value is always an error rather than normalized.
        if strcmp(mode,'derive')&&~isfield(P.ni,name),P.ni.(name)=false;end
        assert(isfield(P.ni,name)&&binary(P.ni.(name)), ...
            'sar20RA:coverageFlags','Missing/nonbinary NI label %s.',name);
    end
    P=coverage_flag(P,'ra_finite_gain',isfinite(P.backend.ra.A0),mode, ...
        'sar20RA:coverageGain','ra_finite_gain must match actual A0.');
    P=coverage_flag(P,'ra_finite_bandwidth',isfinite(P.backend.ra.UGB_hz),mode, ...
        'sar20RA:coverageBandwidth','ra_finite_bandwidth must match actual UGB.');
    assert(isfield(P,'front')&&isstruct(P.front)&&isscalar(P.front)&& ...
        all(isfield(P.front,{'tau_sample_s','unit_cap_f','C_f','group_C_f','mismatch_enabled','Cp_f', ...
            'ktc_enabled','temperature_K','jitter'})), ...
        'sar20RA:coverageFront','Prepared front physical parameters are required.');
    t=P.front.tau_sample_s;
    assert(isa(t,'double')&&isreal(t)&&numel(t)==18&&all(~isnan(t(:))&t(:)>=0), ...
        'sar20RA:coverageSampling','Sampling tau must be 18 nonnegative values; Inf means hold.');
    ktc=P.front.ktc_enabled;
    temp=P.front.temperature_K;
    assert(binary(ktc)&&isa(temp,'double')&&isreal(temp)&&isscalar(temp)&&isfinite(temp)&&temp>=0, ...
        'sar20RA:coverageKTC','Explicit kT/C flag and finite nonnegative temperature required.');
    single=isfield(P.front,'single_bank')&&isequal(P.front.single_bank,true);
    % Only the first eight rows participate in the new single-bank kTC mode.
    % Retain the historical OFF calculation to preserve legacy outputs.
    tCoverage=t(:);if single&&logical(ktc),tCoverage=t(1:8);end
    finiteEffect=any(isfinite(tCoverage)&tCoverage>0);
    P=coverage_flag(P,'sample_settling',finiteEffect,mode, ...
        'sar20RA:coverageSampling','sample_settling counts positive finite sampling tau only.');
    ktcTauOK=all(t(:)==0)||(single&&all(t(1:8)==t(1)));
    assert(~logical(ktc)||ktcTauOK,'sar20RA:coverageKTC', ...
        'Finite-RC kT/C requires equal-tau segments in one single bank.');
    % Inf retains the old B but produces no new Johnson innovation.
    ktcActive=logical(ktc)&&temp>0&&~(single&&isinf(t(1)));
    P=coverage_flag(P,'sample_ktc',ktcActive,mode, ...
        'sar20RA:coverageKTC','sample_ktc must reflect enabled nonzero thermal innovation.');
    j=P.front.jitter;
    normalized=behavior_jitter_parameters(j);
    assert(isequaln(j,normalized),'sar20RA:coverageJitter','Jitter settings must be normalized and complete.');
    coarse=P.calendar(strcmp({P.calendar.type},'coarse_latch'));
    assert(isscalar(coarse)&&j.first_coarse_offset_s==coarse.time_s&& ...
        (~j.enabled||all(t(:)==0)),'sar20RA:coverageJitter', ...
        'Jitter calendar binding or fully settled sampling requirement differs.');
    jitterEffect=j.enabled&&(j.common_sigma_s>0||j.local_sigma_s>0||any(j.fixed_slice_skew_s~=0));
    P=coverage_flag(P,'jitter',jitterEffect,mode, ...
        'sar20RA:coverageJitter','jitter must reflect enabled nonzero aperture error.');
    u=P.front.unit_cap_f;
    C=P.front.C_f;
    assert(isa(u,'double')&&isreal(u)&&isscalar(u)&&isfinite(u)&&u>0&& ...
        isa(C,'double')&&isreal(C)&&isequal(size(C),[18 38])&&all(isfinite(C(:)))&& ...
        binary(P.front.mismatch_enabled),'sar20RA:coverageCap','Valid frontend C and mismatch flag required.');
    if isfield(P.front,'single_bank')&&P.front.single_bank
        assert(all(C(:,1:37)>0,'all')&&all(C(:,38)==0),'sar20RA:coverageCap', ...
            'Single bank needs 37 positive groups and a disconnected bias column.');
    else
        assert(all(C(:)>0),'sar20RA:coverageCap','Pool capacitors must remain positive.');
    end
    expectedGroups=[sum(C(:,1:33),2),sum(C(:,34:37),2),C(:,38)];
    actualGroups=P.front.group_C_f;
    assert(isa(actualGroups,'double')&&isreal(actualGroups)&&isequal(size(actualGroups),[18 3])&& ...
        isequal(typecast(actualGroups(:),'uint64'),typecast(expectedGroups(:),'uint64')), ...
        'sar20RA:staleGroupC','group_C_f must equal exact existing C_f group sums.');
    nominal=u*repmat([16 32*ones(1,31) 16 8 4 2 1 17],18,1);
    if isfield(P.front,'single_bank')&&P.front.single_bank,nominal(:,38)=0;end
    frontDiff=~isequal(C,nominal);
    assert(logical(P.front.mismatch_enabled)||~frontDiff, ...
        'sar20RA:coverageCap','Non-nominal frontend C requires mismatch enabled.');
    ctDiff=false;
    if P.backend.ni.cap_mismatch
        % Keep the existing OU ON shape contract. The historical OU OFF kernel
        % also permits independently valid 6+6 and 10+2 CT splits; their
        % differently shaped capacitor arrays still count as non-nominal.
        sameShape=logical(P.backend.ni.ra_noise);
        mainDiff=network_diff(P.backend.ct.net_actual,P.backend.ct.net_nominal,sameShape);
        replicaDiff=network_diff(P.backend.ct.net_replica,P.backend.ct.net_nominal,sameShape);
        % Replica only influences the numerical path through CINC kick. If its
        % switching is disabled, its passive load still enters output_load.
        effectiveReplica=false;
        if P.backend.ni.cinc_kick
            if P.backend.ct.replica_enabled,effectiveReplica=replicaDiff;
            else,effectiveReplica=~isequal(replica_load(P.backend.ct.net_replica), ...
                    replica_load(P.backend.ct.net_nominal));end
        end
        ctDiff=mainDiff||effectiveReplica;
    end
    P=coverage_flag(P,'cap_mismatch',frontDiff||ctDiff,mode, ...
        'sar20RA:coverageCap','cap_mismatch must reflect selected actual C arrays, not just an enabled flag.');
    assert(isfield(P.backend.ct,'output_parasitic_half_f'), ...
        'sar20RA:coverageParasitic','RA output-load metadata is missing.');
    cp=P.front.Cp_f;
    out=P.backend.ct.output_parasitic_half_f;
    assert(isa(cp,'double')&&isreal(cp)&&numel(cp)==18&&all(isfinite(cp(:))&cp(:)>=0)&& ...
        isa(out,'double')&&isreal(out)&&numel(out)==2&&all(isfinite(out(:))&out(:)>=0), ...
        'sar20RA:coverageParasitic','Valid front Cp and RA output loads required.');
    narrow=any(cp(:)>0)||(logical(P.backend.ni.cinc_kick)&&any(out(:)>0));
    P=coverage_flag(P,'parasitic',narrow,mode,'sar20RA:coverageParasitic', ...
        'parasitic covers front Cp / active RA output load only, not all CT parasitics.');
end

function P=coverage_flag(P,name,expected,mode,id,message)
    if strcmp(mode,'derive'),P.ni.(name)=logical(expected);
    else,assert(logical(P.ni.(name))==logical(expected),id,message);end
end

function different=network_diff(actual,nominal,requireSameShape)
    keys={'cinc_f','bridge_f','main_f','sub_f','track_f','parasitic_main_f','parasitic_sub_f','dummy_f'};
    different=false;
    for k=1:numel(keys)
        name=keys{k};assert(isfield(actual,name)&&isfield(nominal,name), ...
            'sar20RA:coverageCap','CT network missing physical field %s.',name);
        a=actual.(name);
        n=nominal.(name);
        assert(isa(a,'double')&&isa(n,'double')&&isreal(a)&&isreal(n)&& ...
            (~requireSameShape||isequal(size(a),size(n)))&& ...
            all(isfinite(a(:))&a(:)>=0)&&all(isfinite(n(:))&n(:)>=0), ...
            'sar20RA:coverageCap','Invalid CT physical capacitance %s.',name);
        if ~requireSameShape&&strcmp(name,'bridge_f')&& ...
                isvector(a)&&isvector(n)&&numel(a)==2&&numel(n)==2
            % Both CT and replica_load consume bridge_f only by side index.
            % A row/column transpose alone does not change either half.
            same=isequal(a(:),n(:));
        else
            % Do not normalize CINC or other shapes: their full-array use may
            % have shape-dependent behavior beyond side-indexed evaluation.
            same=isequal(a,n);
        end
        different=different||~same;
    end
end

function load=replica_load(net)
% Same two half-network solve and effective output-load definition as CT kernel.
    load=zeros(2,1);
    for side=1:2
        cs=net.cinc_f(side);
        cb=net.bridge_f(side);
        a=cs+sum(net.main_f(side,:))+cb+net.parasitic_main_f(side);
        b=sum(net.sub_f(side,:))+sum(net.track_f(side,:))+net.dummy_f(side)+cb+net.parasitic_sub_f(side);
        matrix=[a -cb;-cb b];
        assert(all(isfinite(matrix(:)))&&rcond(matrix)>0,'sar20RA:coverageCap','Invalid CT load matrix.');
        gain=matrix\[cs;0];load(side)=cs*(1-gain(1));
    end
end

function yes=binary(v)
    yes=(isnumeric(v)||islogical(v))&&isreal(v)&&isscalar(v)&& ...
        isfinite(double(v))&&any(double(v)==[0 1]);
end
