function report=sar20_ou_label_selftest(Pon)
%SAR20_OU_LABEL_SELFTEST Isolated exact-label negative tests. NOT YET RUN.
% Pon must be the actual prepared v3 OU ON N8 P; candidate guard/probe must
% resolve to the frozen overlay. This test never touches a model or RNG.
    assert(isstruct(Pon)&&Pon.backend.ni.ra_noise&&Pon.ni.ra_noise&& ...
        Pon.backend.ra_noise.sigma_vx_rms>0&&isa(Pon.backend.ra_noise.seed_u64,'uint64'), ...
        'sar20OU:labelTestP','Require the actual prepared OU ON P.');
    rng0=rng;base='原有OFF图注 | A=1';
    % OFF keeps the existing byte sequence even if inactive σ/seed remain.
    off=Pon;off.backend.ni.ra_noise=false;off.ni.ra_noise=false;
    assert(isequal(sar20_ou_label_probe(off,base),base), ...
        'sar20OU:labelOff','OFF changed text while stale sigma/seed remained.');
    zero=Pon;zero.backend.ra_noise.sigma_vx_rms=0;zero.ni.ra_noise=false;
    txt0=sar20_ou_label_probe(zero,base);
    assert(startsWith(txt0,base)&&contains(txt0,'sigmaVX(差分VX固定极点稳态RMS)=0 V rms')&& ...
        contains(txt0,'零激励，不计噪声覆盖'), ...
        'sar20OU:labelZero','Sigma-zero label or coverage is wrong.');
    limit=Pon;limit.control.sar2.limit_v=Inf;
    assert(contains(sar20_ou_label_probe(limit,base),'SAR2过量程检测关闭(+Inf)'), ...
        'sar20OU:labelLimit','Inf limit must visibly indicate disabled range test.');
    % Adjacent binary64 sigma values must not collapse to one display.
    a=Pon;b=Pon;sig=a.backend.ra_noise.sigma_vx_rms;
    b.backend.ra_noise.sigma_vx_rms=sig+eps(sig);
    assert(b.backend.ra_noise.sigma_vx_rms>sig, ...
        'sar20OU:labelULP','Cannot form adjacent positive sigma.');
    ta=sar20_ou_label_probe(a,base);tb=sar20_ou_label_probe(b,base);
    assert(~strcmp(ta,tb)&&contains(ta,sprintf('sigmaVX(差分VX固定极点稳态RMS)=%.17g V rms',sig))&& ...
        contains(tb,sprintf('sigmaVX(差分VX固定极点稳态RMS)=%.17g V rms',b.backend.ra_noise.sigma_vx_rms)), ...
        'sar20OU:labelULP','Adjacent sigma displays collapsed.');
    % Construct uint64 values without converting 2^53+1 or max through double.
    k=bitshift(uint64(1),53);seeds=[k bitor(k,uint64(1)) intmax('uint64')];
    expected={'0020000000000000','0020000000000001','FFFFFFFFFFFFFFFF'};
    values=cell(1,3);
    for i=1:3
        p=Pon;p.backend.ra_noise.seed_u64=seeds(i);values{i}=sar20_ou_label_probe(p,base);
        assert(contains(values{i},['seed=0x' expected{i}]), ...
            'sar20OU:labelSeed','uint64 seed display lost bits.');
    end
    assert(numel(unique(values))==3&&isequaln(rng0,rng), ...
        'sar20OU:labelSeed','Distinct seed displays or RNG guard failed.');
    report=struct('status','candidate_label_contract_passed', ...
        'sigma_adjacent_distinct',true,'seeds_hex',{expected}, ...
        'sigma0_not_covered',true,'off_text_unchanged',true, ...
        'scope','Isolated exact-code probe; actual applied model/visual graph still requires separate checks.');
end
