function [q,Q]=sar20_pp_parameters(P)
%SAR20_PP_PARAMETERS Compile-time binding of actual model-workspace P.
% OFF is exact bypass. ON permits only the pinned, independently checked M8
% behavioral qualification and two preloaded immutable versions. No analog
% C/held/residual fields are read or propagated into q. Same-chip provenance
% is a separate trusted run-controller gate; public fields alone cannot prove it.
    assert(isstruct(P)&&isscalar(P)&&isfield(P,'bank')&&isstruct(P.bank)&& ...
        isscalar(P.bank)&&isfield(P.bank,'enabled')&&binary(P.bank.enabled)&& ...
        isfield(P,'groups')&&isstruct(P.groups)&&isfield(P,'transport')&& ...
        isfield(P.transport,'enabled')&&binary(P.transport.enabled), ...
        'pp:appliedP','Use explicit applied bank/transport/groups fields.');
    q=struct('enabled',logical(P.bank.enabled),'n_groups',double(numel(P.groups)));Q=[];
    if ~q.enabled,return;end
    sar20_bank_require_actual_binding(P);
    required={'slots','qualification_file','initial_slot','lead_samples','command_schedule','provenance_scope'};
    assert(isequal(sort(fieldnames(P.bank)),sort([{'enabled'};required(:)])), ...
        'pp:bankFields','Exactly the declared public bank parameters are required.');
    assert(ischar(P.bank.provenance_scope)&&strcmp(P.bank.provenance_scope,'TRAIN_P_WHITELIST_CONTROLLER_ONLY'), ...
        'pp:provenance','Requires the controlled saved-TRAIN-P construction; this self-report is not anti-tamper proof.');
    assert(P.transport.enabled&&q.n_groups==49&&isfield(P.transport,'public_en')&& ...
        P.transport.public_en==10&&isfield(P,'training')&&isfield(P.training,'enabled')&& ...
        ~P.training.enabled&&isfield(P,'cal_cfg')&&isfield(P.cal_cfg,'enabled')&& ...
        ~P.cal_cfg.enabled&&~P.frozen.enabled,'pp:mode', ...
        'Bank ON requires normal RX, old Train/Frozen OFF, digital off and tau0.');
    assert(isfield(P,'calendar')&&isstruct(P.calendar)&&all(isfield(P.calendar,{'type','index','bit'})), ...
        'pp:calendar','Need actual applied public M8 calendar.');
    comp=P.calendar(strcmp({P.calendar.type},'ta_compare'));
    feed=P.calendar(strcmp({P.calendar.type},'ta_feedback'));
    assert(numel(comp)==8&&numel(feed)==7&&isequal([comp.index],0:7)&& ...
        isequal([comp.bit],7:-1:0)&&isequal([feed.index],0:6)&&isequal([feed.bit],7:-1:1)&& ...
        isfield(P.backend,'ct')&&P.backend.ct.net_nominal.tracking_count==7&& ...
        strcmp(P.digital.tracking_mode,'finite_sinc2'),'pp:tracking', ...
        'unsupported_m1_no_fit: only actual M8 eight comparisons/seven feedback with finite_sinc2 are qualified.');
    f=P.bank.qualification_file;
    assert(ischar(f)&&isrow(f)&&isfile(f),'pp:qualificationFile','Require the pinned real qualification file.');
    fid=fopen(f,'rb');assert(fid>=0,'pp:qualificationFile','Cannot open qualification.');
    closeFile=onCleanup(@()fclose(fid));bytes=fread(fid,inf,'*uint8');clear closeFile;
    Q=sar20_pp_qualification_from_bytes(bytes); % same verified bytes are parsed ONCE
    assert(strcmp(Q.schema,'sar20-behavior-bank-qualification/v1')&& ...
        strcmp(Q.status,'behavior_profile_qualified')&&strcmp(Q.kind,'registered_behavior_simulation')&& ...
        ~Q.fixture&&strcmp(Q.acceptance,'NOT_ACCEPTED')&&strcmp(Q.activation,'none')&& ...
        Q.m8_comparisons==8&&Q.physical_feedback_count==7&& ...
        isequal(reshape(Q.tracking_weight_numerators,1,[]),8:-1:1)&&Q.tracking_weight_denominator==8&& ...
        strcmp(Q.digital_tracking_mode,'finite_sinc2')&&strcmp(Q.digital_calibration_mode,'off')&& ...
        Q.train_recheck.rank_independent==684&&Q.train_recheck.fit_calls_original==1&& ...
        Q.fixed_holdout_gates.passed&&~Q.actual_c_or_held_read&&~Q.refit, ...
        'pp:qualification','Real independent qualification/lifecycle/M8 gate failed.');
    profile_check(P,Q.public_profile);source_check(Q.algorithm_source_sha256);
    slots=P.bank.slots;
    assert(isstruct(slots)&&numel(slots)==2&&isequal(sort(fieldnames(slots)),sort({'version';'cache'})), ...
        'pp:slots','Provide exactly two immutable slot versions.');
    q.slot=cell(2,1);versions=zeros(1,2);
    for k=1:2
        versions(k)=slots(k).version;
        assert(integer(versions(k),1,2^32-1),'pp:version','Nonzero uint32 version required.');
        C=slots(k).cache;
        cacheFields={'schema';'public_cfg';'h';'h_by_slice';'plan';'coefficient_sha256'; ...
            'public_cfg_sha256';'lifecycle';'acceptance'};
        assert(isstruct(C)&&isscalar(C)&&isequal(sort(fieldnames(C)),sort(cacheFields))&& ...
            isequaln(C,behavior_frozen_setup(C.public_cfg,C.h))&& ...
            isequaln(C.public_cfg,P.cal_cfg.public_cfg)&& ...
            isequal(double(C.plan),double(P.front.plan))&& ...
            strcmp(C.coefficient_sha256,Q.coefficient_sha256)&& ...
            strcmp(C.public_cfg_sha256,Q.public_cfg_sha256)&& ...
            strcmp(sar20_bank_sha256(uint8(C.plan(:))),Q.plan_sha256), ...
            'pp:payload','Slot h/cfg/actual P public plan/qualification differ.');
        q.slot{k}=C; % public h/cfg/plan only; never full P
    end
    assert(versions(1)<versions(2),'pp:versions','A/B version IDs must increase for frozen v3 LOAD.');
    assert(integer(P.bank.initial_slot,1,2)&&integer(P.bank.lead_samples,2,1e6), ...
        'pp:control','Initial qualified slot and proven lead G>=2 required.');
    q.scope='PRELIMINARY_PUBLIC_ONLY';q.versions=versions;q.initial_slot=double(P.bank.initial_slot);
    q.lead_samples=double(P.bank.lead_samples);q.epoch=double(P.epoch);q.first_ready_id=0;
    assert(integer(q.epoch,1,16),'pp:epoch','Use actual RX normal epoch 1..16.');
    schedule=P.bank.command_schedule;
    assert(isa(schedule,'double')&&isreal(schedule)&&size(schedule,2)==6&& ...
        all(isfinite(schedule(:)))&&all(schedule(:)==floor(schedule(:)))&& ...
        all(schedule(:,1)>=0)&&numel(unique(schedule(:,1)))==size(schedule,1), ...
        'pp:schedule','Public schedule rows [hit,op,id,slot,version,arg] must be finite integer and unique hit.');
    q.command_schedule=schedule;
end
function profile_check(P,reference)
    paths={'seed','front/schema','front/mismatch_enabled','front/unit_cap_f','front/vref_v', ...
      'front/temperature_K','front/ktc_enabled','front/ktc_seed','front/tau_dac_s', ...
      'front/tau_sample_s','front/tau_precharge_s','front/dem_enabled','front/dem_seed', ...
      'front/dither_enabled','front/dither_seed','front/dither_input_amplitude_v','front/pool_seed', ...
      'front/plan_rows','front/jitter/enabled','front/jitter/common_sigma_s','front/jitter/local_sigma_s', ...
      'front/jitter/fixed_slice_skew_s','front/jitter/first_coarse_offset_s','front/jitter/seed', ...
      'backend/ra/A0','backend/ra/Cf_f','backend/ra/UGB_hz','backend/ra/slew_v_per_s', ...
      'backend/ra/tau_reset_s','backend/ra/vos_input_v','backend/ct/reference_v', ...
      'backend/ct/net_nominal/tracking_count', ...
      'digital/tracking_mode','digital/tracking_step_ra_v','backend/az/mode','backend/az/leak_tau_s', ...
      'backend/az/write_tau_s','backend/az/write_start_s','backend/az/write_end_s', ...
      'backend/dac_coupling/enabled','digital/calibration_mode','transport/enabled'};
    for k=1:numel(paths)
        parts=strsplit(paths{k},'/');actual=P;
        for j=1:numel(parts),assert(isstruct(actual)&&isfield(actual,parts{j}),'pp:profileFields','Missing %s.',paths{k});actual=actual.(parts{j});end
        key=matlab.lang.makeValidName(paths{k});assert(isfield(reference,key),'pp:profileFields','Qualification lacks %s.',paths{k});
        expected=reference.(key);
        if ischar(actual),same=ischar(expected)&&strcmp(actual,expected);
        else
            if iscell(expected)
                vals=zeros(numel(expected),1);for j=1:numel(expected),vals(j)=number(expected{j});end
            elseif ischar(expected),vals=number(expected);else,vals=double(expected(:));end
            same=(isnumeric(actual)||islogical(actual))&&isreal(actual)&& ...
                isequaln(double(actual(:)),double(vals(:)));
        end
        assert(same,'pp:profile','Actual public P differs at %s.',paths{k});
    end
end
function x=number(x)
    if ischar(x),x=str2double(x);end
    assert(isnumeric(x)&&isreal(x)&&isscalar(x),'pp:profile','Bad profile scalar.');x=double(x);
end
function source_check(s)
    names={'behavior_frozen_setup','behavior_frozen_step','behavior_public_cal_features','behavior_calendar','behavior_sar_step'};
    for k=1:numel(names)
        f=which(names{k});key=matlab.lang.makeValidName([names{k} '.m']);
        assert(~isempty(f)&&isfield(s,key)&&strcmp(file_sha(f),s.(key)), ...
            'pp:algorithm','Resolved %s source differs from qualified M8 algorithm.',names{k});
    end
end
function h=file_sha(p)
    f=fopen(p,'rb');assert(f>=0,'pp:file','Cannot open qualification/source.');c=onCleanup(@()fclose(f)); %#ok<NASGU>
    md=java.security.MessageDigest.getInstance('SHA-256');while ~feof(f),md.update(fread(f,1048576,'*uint8'));end
    h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function y=binary(x),y=(isnumeric(x)||islogical(x))&&isreal(x)&&isscalar(x)&&isfinite(double(x))&&any(double(x)==[0 1]);end
function y=integer(x,a,b),y=isnumeric(x)&&isreal(x)&&isscalar(x)&&isfinite(x)&&x==floor(x)&&x>=a&&x<=b;end
