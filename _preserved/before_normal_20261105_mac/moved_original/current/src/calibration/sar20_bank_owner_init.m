function S=sar20_bank_owner_init(cfg,plan,profile,authority,epoch,first_id,guard_samples)
%SAR20_BANK_OWNER_INIT Isolated A/B diagnostic state; never enables production.
% cfg is public cfg17, plan is its complete [plan_rows x 8] public calendar;
% profile carries external chip/profile labels and declared tauDAC18 [s].
% authority contains separate trusted digest lists for training, independent
% qualification and consumer-drain certificates. epoch/first_id are the actual
% declared first RX tag; guard_samples is an externally proven publish lead.
% Pure value struct, no P/ADC held/actual C/reference sample/persistent state.
% This standalone candidate has NO binding to the actual applied model P; its
% declared tau0 check is necessary but not sufficient for real activation.
% All outputs remain diagnostic until a future verified integration provides
% actual-P compile/enable gating and the caller's trusted certificate checks.
    assert(isstruct(profile)&&isscalar(profile)&& ...
        isequal(sort(fieldnames(profile)),sort({'schema';'chip_id';'profile_id';'tau_dac_s'}))&& ...
        strcmp(profile.schema,'sar20-bank-profile/v1')&&text_scalar(profile.chip_id)&& ...
        text_scalar(profile.profile_id),'bankOwner:profile','Require the exact declared public profile.');
    tau=profile.tau_dac_s;
    assert(isa(tau,'double')&&isreal(tau)&&isequal(size(tau),[18 1])&& ...
        all(isfinite(tau))&&all(tau==0),'bankOwner:tau', ...
        'Only declared tauDAC18=0 is modeled; actual P still needs compile/enable gating.');
    names={'mode';'approved_training_sha256';'approved_qualification_sha256';'approved_drain_sha256'};
    assert(isstruct(authority)&&isscalar(authority)&&isequal(sort(fieldnames(authority)),sort(names))&& ...
        ischar(authority.mode)&&isrow(authority.mode)&& ...
        any(strcmp(authority.mode,{'fixture_only','registered'})), ...
        'bankOwner:authority','Supply an explicit domain and separate preverified digest lists.');
    for key=names(2:end).'
        anchors=authority.(key{1});assert(iscell(anchors)&&(isempty(anchors)||isvector(anchors)), ...
            'bankOwner:authority','Digest list must be an empty or vector cell array.');
        for k=1:numel(anchors),assert(hex64(anchors{k}),'bankOwner:authorityHash','Bad digest anchor.');end
        assert(numel(unique(anchors))==numel(anchors),'bankOwner:authorityHash','Duplicate digest anchors.');
    end
    assert(isnumeric(epoch)&&isreal(epoch)&&isscalar(epoch)&&isfinite(epoch)&& ...
        epoch==floor(epoch)&&epoch>=1&&epoch<=16,'bankOwner:epoch', ...
        'Use a declared public startup epoch 1..16; runtime reset needs a new run.');
    assert(isnumeric(guard_samples)&&isreal(guard_samples)&&isscalar(guard_samples)&& ...
        isfinite(guard_samples)&&guard_samples==floor(guard_samples)&&guard_samples>=2&& ...
        guard_samples<=1e6,'bankOwner:guard', ...
        'Provide a separately justified public lead G>=2; this owner cannot prove system timing.');
    probe=behavior_frozen_setup(cfg,ones(684,1));
    assert(isnumeric(plan)&&isreal(plan)&&isequal(size(plan),size(probe.plan))&& ...
        all(isfinite(double(plan(:))))&&isequal(double(plan),double(probe.plan)), ...
        'bankOwner:plan','Public plan must exactly match cfg17 schedule/seed/shape.');
    assert(isnumeric(first_id)&&isreal(first_id)&&isscalar(first_id)&&isfinite(first_id)&& ...
        first_id==floor(first_id)&&first_id>=0&&first_id<=double(cfg.plan_rows)-2, ...
        'bankOwner:firstID','Declare the first actual RX-ready ID, within the public plan.');
    profile.tau_dac_s=double(tau);plan=uint8(plan);
    profile_sha=sar20_bank_sha256(unicode2native(jsonencode(orderfields(profile)),'UTF-8'));
    authority_sha=sar20_bank_sha256(unicode2native(jsonencode(orderfields(authority)),'UTF-8'));
    slot=struct('state','empty','version',0,'h',zeros(684,1),'coefficient_sha256','', ...
        'training_certificate_sha256','','qualification_certificate_sha256','', ...
        'protocol_sha256','','proof_kind','');
    transition=struct('pending',false,'old_slot',0,'new_slot',0,'epoch',0, ...
        'activation_id',-1,'switched',false,'first_new_valid_id',-1);
    S=struct('schema','sar20-bank-owner-state/v4','scope','ISOLATED_UNBOUND_DIAGNOSTIC_ONLY', ...
        'cfg',cfg,'plan',plan,'public_cfg_sha256',probe.public_cfg_sha256, ...
        'plan_sha256',sar20_bank_sha256(plan(:)),'profile',profile,'profile_sha256',profile_sha, ...
        'authority',authority,'authority_sha256',authority_sha,'epoch',double(epoch),'first_id',double(first_id), ...
        'guard_samples',double(guard_samples),'slots',repmat(slot,2,1),'active_slot',0, ...
        'max_version',0,'transition',transition,'has_rx',false,'last_rx_id',-1, ...
        'faulted',false,'fault_reason','','event_count',0,'last_hit',-1, ...
        'last_signature',[],'last_output',[],'last_command_id',0, ...
        'last_command_sha256','','last_command_status','');
end
function ok=text_scalar(x),ok=ischar(x)&&isrow(x)&&~isempty(x);end
function ok=hex64(x),ok=ischar(x)&&isrow(x)&&~isempty(regexp(x,'^[0-9a-f]{64}$','once'))&&~all(x=='0');end
