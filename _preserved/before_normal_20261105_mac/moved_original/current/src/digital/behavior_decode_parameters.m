function p=behavior_decode_parameters(saved,vref_v,az_mode)
%BEHAVIOR_DECODE_PARAMETERS Copy public nominal reconstruction coefficients.
%Version: v1 (2026-10-27). Caller: behavior initializer before behavior_decode.
%Inputs saved is the small nominal.mat design struct supplied by adc_parameters;
%vref_v [V] is the frontend reference, az_mode defaults off.
%CHOP integration MUST pass the same configured mode as the backend/routing.
%FSR/reference/weights [V], ra_gain [1], dither amplitude [V]/seed [integer].
%No actual capacitor/network/state is inspected; no retained state/reset or RNG.
%Model: nominal finite-sinc2, calibration off; training/frozen calibration is rejected.
%Geometry changes require consistent analog networks AND nominal digital weights,
%offsets/scales and the fixed DAC1 profile in behavior_decode/the built graph.
%Editing binary.nominal alone does not regenerate these inputs or rederive all weights;
%this function copies saved.fpga coefficients and performs no geometry extraction.
    assert(isstruct(saved)&&isfield(saved,'fpga')&&isfield(saved,'calibration'), ...
        'behaviorDecode:config','Require saved nominal FPGA/calibration configuration.');
    if nargin<3,az_mode='off';end
    behavior_public_pol(0,0,az_mode); % validate only public mode; no state access
    f=saved.fpga;
    assert(strcmp(saved.calibration.mode,'off')&&~f.cal_enable&&~f.cal_training, ...
        'behaviorDecode:calibration','Calibration is not implemented; require off.');
    assert(strcmp(f.dt_encoding,'bipolar_from_raw_bits')&&f.sinc2_scale==1/8, ...
        'behaviorDecode:tracking','Require the explicit eight-comparison bipolar tracking profile.');
    p=struct('schema','sar20-behavior-decode/v1','vref_v',double(vref_v), ...
        'fsr_diff_v',double(f.fsr_diff_v),'ra_gain',double(f.ra_gain), ...
        'd2_weights_ra_v',double(f.weights.d2(:)), ...
        'd2_offset_ra_v',double(f.weights.d2_offset_v), ...
        'tracking_step_ra_v',double(f.tracking_scale_v), ...
        'dither_enabled',logical(f.dither_enable),'dither_seed',double(f.dither_seed), ...
        'dither_amplitude_v',double(f.dither_amplitude_v),'calibration_mode','off', ...
        'tracking_mode','finite_sinc2','az_mode',char(az_mode), ...
        'coefficient_source','nominal saved.fpga weights only; new DAC1 geometry formula');
end
